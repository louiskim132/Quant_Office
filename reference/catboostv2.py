def _fit_one(X_fit, y_fit, X_inner, y_inner, cat_features, model_params, seed):
    from catboost import CatBoostClassifier, Pool
    model_params = resolve_model_params(model_params)
    fit_pool = Pool(X_fit, y_fit, cat_features=cat_features)
    inner_pool = Pool(X_inner, y_inner, cat_features=cat_features)
    model = CatBoostClassifier(loss_function="Logloss", random_seed=seed,
                               **model_params)
    # S1 / S7: early stopping resolves against the INNER slice only. Never
    # eval_set=test_pool -- that was the pre-R6 defect worth 0.04-0.06 AUC.
    model.fit(fit_pool, eval_set=inner_pool)
    return model


