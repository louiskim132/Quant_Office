# ---------------------------------------------------------------------------
# S11 -- per-arm checkpointing and resume
# ---------------------------------------------------------------------------
# S11 asked for per-arm persistence as arms complete: at ~2,900 fits a Colab
# disconnect otherwise costs the whole run, and with no resume path a restart
# redoes Arm P's confirmatory fits before reaching the diagnostics that were
# lost. Checkpoints are keyed by ARM, not by run_tag, so they survive a new
# session.
#
# A checkpoint is only reusable if it was produced under the SAME configuration.
# Without that guard, resume becomes a way to silently blend results from two
# different configurations -- which would be a provenance failure, not a
# convenience. Every checkpoint therefore carries a fingerprint of the governing
# constants and is refused when it does not match.
RESUME = True
CHECKPOINT_DIR = os.path.join(RESULTS_DIR, "m1_checkpoints")


def config_fingerprint(payload):
    """Stable hash of the constants that govern a walk-forward arm."""
    import hashlib
    return hashlib.sha256(repr(sorted(payload.items())).encode()).hexdigest()[:16]


def _checkpoint_paths(arm_label):
    base = os.path.join(CHECKPOINT_DIR, arm_label)
    return base + "_oof.parquet", base + "_results.csv", base + "_inner.csv", base + "_meta.json"


def save_arm_checkpoint(arm_label, fingerprint, results, oof, inner):
    """Persist one arm's frames as soon as it completes."""
    import json
    if not os.path.isdir(RESULTS_DIR):
        return False
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    oof_p, res_p, inner_p, meta_p = _checkpoint_paths(arm_label)
    try:
        oof.to_parquet(oof_p)
    except Exception:                                       # noqa: BLE001
        oof_p = oof_p.replace(".parquet", ".csv")
        oof.to_csv(oof_p, index=False, float_format="%.6f")
    results.to_csv(res_p, index=False)
    inner.to_csv(inner_p, index=False)
    with open(meta_p, "w", encoding="utf-8") as fh:
        json.dump({"arm": arm_label, "fingerprint": fingerprint,
                   "run_tag": run_tag, "n_folds": int(len(results)),
                   "n_oof_rows": int(len(oof)), "oof_file": os.path.basename(oof_p)},
                  fh, indent=2)
    print("  checkpointed " + arm_label + " (" + str(len(results)) + " folds)")
    return True


def load_arm_checkpoint(arm_label, fingerprint):
    """Return (results, oof, inner) from a matching checkpoint, else None.

    Refuses a checkpoint whose fingerprint differs: a stale one from another
    configuration must never be blended into this run.
    """
    import json
    if not RESUME:
        return None
    oof_p, res_p, inner_p, meta_p = _checkpoint_paths(arm_label)
    if not os.path.exists(meta_p):
        return None
    try:
        with open(meta_p, encoding="utf-8") as fh:
            meta = json.load(fh)
    except Exception:                                       # noqa: BLE001
        return None
    if meta.get("fingerprint") != fingerprint:
        print("  IGNORING stale checkpoint for " + arm_label
              + " (fingerprint " + str(meta.get("fingerprint"))
              + " != " + fingerprint + ") -- configuration changed, recomputing")
        return None
    stored = os.path.join(CHECKPOINT_DIR, meta.get("oof_file", ""))
    try:
        oof = (pd.read_parquet(stored) if stored.endswith(".parquet")
               else pd.read_csv(stored, parse_dates=["time"]))
        results = pd.read_csv(res_p, parse_dates=["test_start"])
        inner = pd.read_csv(inner_p)
    except Exception as exc:                                # noqa: BLE001
        print("  checkpoint for " + arm_label + " unreadable: " + repr(exc)[:100])
        return None
    print("  RESUMED " + arm_label + " from checkpoint ("
          + str(len(results)) + " folds, run_tag " + str(meta.get("run_tag")) + ")")
    return results, oof, inner


def run_or_resume(arm_label, fingerprint, fn):
    """Run one walk-forward arm, or restore it from a matching checkpoint."""
    cached = load_arm_checkpoint(arm_label, fingerprint)
    if cached is not None:
        return cached
    wf = fn()
    results, oof, inner = wf[0], wf[1], wf[2]
    save_arm_checkpoint(arm_label, fingerprint, results, oof, inner)
    return wf


def annotate_returns(oof_df, direction):
    """Attach gross and net returns to an OOF frame. Ported from
    catboostv2.py L2351-2368, with the per-asset cost model of S10."""
    d = oof_df.dropna(subset=["target", "next_open", "tp_price", "sl_price",
                              "bars_to_resolution"]).copy()
    if len(d) == 0:
        return d
    d["time"] = pd.to_datetime(d["time"])
    d = d.sort_values("time").reset_index(drop=True)
    d["exit_price"] = np.where(d["target"] == 1, d["tp_price"], d["sl_price"])
    if direction == "long":
        d["gross_return"] = (d["exit_price"] - d["next_open"]) / d["next_open"]
    else:
        d["gross_return"] = (d["next_open"] - d["exit_price"]) / d["next_open"]
    d["net_return"] = apply_cost_model(direction, d["next_open"].to_numpy(),
                                       d["exit_price"].to_numpy(),
                                       d["asset"].to_numpy())
    return d


def trades_at_policy(oof_df, direction):
    """PRIMARY selection path: each fold contributes trades at ITS OWN
    pre-registered policy threshold. Folds that stood down contribute nothing,
    and no threshold is ever chosen after seeing test outcomes."""
    d = annotate_returns(oof_df, direction)
    if len(d) == 0:
        return d
    keep = d["policy_threshold"].notna() & (d["prob"] >= d["policy_threshold"])
    return d[keep].reset_index(drop=True)


