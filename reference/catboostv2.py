TRUNCATION_AUDIT_CUTS = 3
TRUNCATION_AUDIT_BUFFER_BARS = 0
TRUNCATION_AUDIT_TOL = 1e-9
TRUNCATION_AUDIT_SEED = 20260822


def run_truncation_audit(frame, feature_cols=None, n_cuts=TRUNCATION_AUDIT_CUTS,
                         feature_fn=None, seed=TRUNCATION_AUDIT_SEED):
    """S9 B3 -- recompute features on truncated copies; assert earlier values
    are unchanged.

    Any lookahead in feature construction breaks one testable property: a
    feature at bar t computed from data through T must equal the same feature at
    bar t computed through any T' > t. The test needs no knowledge of what the
    leak is or where to look.

    G1/S9 CHANGE FROM v2: truncation is by TIMESTAMP, not row index.
    catboostv2.py L2055 used df_source.iloc[:cut], which on a (time, asset)
    frame cuts mid-timestamp and leaves one asset a row the others lack --
    making compute_epoch_id differ across the cut for reasons that are not
    leaks. Cuts are jittered off the regular grid (seeded) because a leak
    perturbing only a periodic subset of rows can miss every regular cut.

    `feature_fn` exists so the planted-leak validation below can substitute a
    deliberately leaky builder. v2 had no such parameter, which is why its
    "4/5 detected at buffer=0" figure was never reproducible in-repo.
    """
    feature_fn = feature_fn or (lambda f: build_features(f, verbose=False))
    full, cols = feature_fn(frame.copy())
    feature_cols = feature_cols or cols

    times = np.sort(frame["time"].unique())
    n = len(times)
    rng = np.random.default_rng(seed)
    rows = []
    for cut_i in range(1, n_cuts + 1):
        base = n * (cut_i / (n_cuts + 1))
        span = n / (n_cuts + 1)
        pos = int(np.clip(base + rng.integers(-span * 0.4, span * 0.4),
                          n * 0.1, n * 0.95))
        cut_ts = pd.Timestamp(times[pos])
        try:
            trunc, _ = feature_fn(frame[frame["time"] < cut_ts].copy())
        except Exception as exc:                                # noqa: BLE001
            rows.append({"cut_ts": cut_ts, "feature": "<build_features>",
                         "status": "BUILD_FAILED", "max_abs_diff": np.nan,
                         "n_mismatched": np.nan, "n_compared": 0,
                         "detail": repr(exc)[:200]})
            continue
        compare_ts = cut_ts - TRUNCATION_AUDIT_BUFFER_BARS * BAR_DELTA
        a_all = full[full["time"] < compare_ts].sort_values(["time", "asset"])
        b_all = trunc[trunc["time"] < compare_ts].sort_values(["time", "asset"])
        if len(a_all) != len(b_all) or len(a_all) < BARS_PER_DAY * 5:
            rows.append({"cut_ts": cut_ts, "feature": "<alignment>",
                         "status": "MISALIGNED", "max_abs_diff": np.nan,
                         "n_mismatched": np.nan, "n_compared": len(b_all),
                         "detail": "full=" + str(len(a_all)) + " trunc=" + str(len(b_all))})
            continue
        for feat in feature_cols:
            if feat not in b_all.columns or feat not in a_all.columns:
                rows.append({"cut_ts": cut_ts, "feature": feat, "status": "MISSING",
                             "max_abs_diff": np.nan, "n_mismatched": np.nan,
                             "n_compared": 0, "detail": ""})
                continue
            a = pd.to_numeric(a_all[feat], errors="coerce").to_numpy(float)
            b = pd.to_numeric(b_all[feat], errors="coerce").to_numpy(float)
            both_nan = np.isnan(a) & np.isnan(b)
            nan_mismatch = np.isnan(a) ^ np.isnan(b)
            diff = np.where(both_nan, 0.0, np.abs(a - b))
            diff = np.where(nan_mismatch, np.inf, np.nan_to_num(diff, nan=np.inf))
            n_bad = int((diff > TRUNCATION_AUDIT_TOL).sum())
            rows.append({
                "cut_ts": cut_ts, "feature": feat,
                "status": "PASS" if n_bad == 0 else "LOOKAHEAD",
                "max_abs_diff": float(np.max(diff)) if len(diff) else 0.0,
                "n_mismatched": n_bad, "n_compared": len(a), "detail": "",
            })
    return pd.DataFrame(rows)


# --- S9 B3 planted leaks ---------------------------------------------------
# These did NOT exist in catboostv2.py. Lines 2006-2023 there record a
# calibration ("4/5 detected at buffer=0") performed elsewhere; nothing in that
# file plants a leak or routes a doctored frame through run_truncation_audit,
# and no parameter would have allowed it. S9 requires the DETECTOR to be
# re-validated, not merely the property to be exercised, so the leaks are
# written here and run on every execution.
def _with_extra(frame, name, values):
    out, cols = build_features(frame, verbose=False)
    out[name] = values
    return out, cols + [name]


def _by_asset(frame, fn):
    return frame.groupby("asset", sort=False)["close"].transform(fn)


PLANTED_LEAKS = {
    # Whole-window statistic: changes with the truncation point by definition.
    "leak_whole_window_median":
        lambda f: _with_extra(f, "leak_whole_window_median",
                              _by_asset(f, lambda s: pd.Series(
                                  np.repeat(s.median(), len(s)), index=s.index))),
    # Direct one-bar lookahead.
    "leak_shift_minus_1":
        lambda f: _with_extra(f, "leak_shift_minus_1", _by_asset(f, lambda s: s.shift(-1))),
    # Longer-range lookahead.
    "leak_shift_minus_5":
        lambda f: _with_extra(f, "leak_shift_minus_5", _by_asset(f, lambda s: s.shift(-5))),
    # Centred window: half the window lies in the future.
    "leak_centred_window":
        lambda f: _with_extra(f, "leak_centred_window",
                              _by_asset(f, lambda s: s.rolling(21, center=True,
                                                               min_periods=1).mean())),
    # Sparse backfill: the L1 limitation case, detectable only when a cut lands
    # on an affected row -- which is why the cuts are jittered.
    "leak_sparse_bfill":
        lambda f: _with_extra(f, "leak_sparse_bfill",
                              _by_asset(f, lambda s: s.where(
                                  np.arange(len(s)) % 50 != 0).bfill())),
}

# L1 is a PRE-EXISTING registered limitation (catboostv2.py L2161+, carried into
# LEAK_AUDIT_KNOWN_LIMITATIONS below): sparse backfill is detected only when a
# cut lands on an affected row, so at n_cuts=3 a miss is the expected outcome,
# not a regression. It is listed here so its miss is RECORDED rather than either
# failing the run or vanishing. This is not a bar being lowered to fit a result
# -- the limitation was registered before this detector existed.
LOW_POWER_PROBES = {"leak_sparse_bfill": "L1 -- probabilistic, low power at n_cuts=3"}

CAUSAL_CONTROLS = {
    "causal_trailing_mean":
        lambda f: _with_extra(f, "causal_trailing_mean",
                              _by_asset(f, lambda s: s.rolling(20, min_periods=20).mean())),
    "causal_ewm":
        lambda f: _with_extra(f, "causal_ewm",
                              _by_asset(f, lambda s: s.ewm(span=20, adjust=False).mean())),
    "causal_trailing_zscore":
        lambda f: _with_extra(f, "causal_trailing_zscore",
                              _by_asset(f, lambda s: (
                                  (s - s.rolling(50, min_periods=50).mean())
                                  / s.rolling(50, min_periods=50).std()))),
    "causal_shift_plus_1":
        lambda f: _with_extra(f, "causal_shift_plus_1", _by_asset(f, lambda s: s.shift(1))),
}


def validate_truncation_detector(frame, n_cuts=TRUNCATION_AUDIT_CUTS):
    """S9 -- re-validate the B3 DETECTOR against planted leaks and causal
    controls.

    The truncation-invariance checks in the test suite exercise the PROPERTY;
    this exercises the DETECTOR. S9 requires the second explicitly, and a
    structural rewrite (timestamp truncation, the G1 grid) is exactly when a
    detector can stop working while still reporting PASS.

    A planted leak that is not flagged is a detector failure. A causal control
    that IS flagged is a false positive and equally a failure.
    """
    rows = []
    for name, fn in PLANTED_LEAKS.items():
        audit = run_truncation_audit(frame, [name], n_cuts=n_cuts, feature_fn=fn)
        detected = bool((audit["status"] == "LOOKAHEAD").any())
        low_power = name in LOW_POWER_PROBES
        if detected:
            verdict = "DETECTED"
        elif low_power:
            verdict = "MISSED_KNOWN_LIMITATION"
        else:
            verdict = "DETECTOR_BLIND"
        rows.append({"probe": name,
                     "kind": "planted_leak_low_power" if low_power else "planted_leak",
                     "expected": "LOOKAHEAD",
                     "observed": "LOOKAHEAD" if detected else "PASS",
                     "verdict": verdict,
                     "known_limitation": LOW_POWER_PROBES.get(name, ""),
                     "n_cuts_flagged": int((audit["status"] == "LOOKAHEAD").sum())})
    for name, fn in CAUSAL_CONTROLS.items():
        audit = run_truncation_audit(frame, [name], n_cuts=n_cuts, feature_fn=fn)
        flagged = bool((audit["status"] == "LOOKAHEAD").any())
        rows.append({"probe": name, "kind": "causal_control",
                     "expected": "PASS",
                     "observed": "LOOKAHEAD" if flagged else "PASS",
                     "verdict": "FALSE_POSITIVE" if flagged else "CLEAN",
                     "known_limitation": "",
                     "n_cuts_flagged": int((audit["status"] == "LOOKAHEAD").sum())})
    out = pd.DataFrame(rows)
    planted = out[out["kind"].str.startswith("planted_leak")]
    out["detection_rate"] = round(
        float((planted["verdict"] == "DETECTED").mean()), 4)
    # The audit fails only on an UNEXPECTED miss or any false positive. A miss on
    # a registered low-power probe is recorded, not a failure.
    out["detector_ok"] = bool((out["verdict"] != "DETECTOR_BLIND").all()
                              and (out["verdict"] != "FALSE_POSITIVE").all())
    return out


def validate_alignment_detector(featured, m_by_asset, direction="long",
                                shifts=(-1, 1), model_params=None,
                                fold_kwargs=None):
    """R9 -- plant a known misalignment and confirm the pipeline detects it.

    B3 validates feature CONSTRUCTION; B4 validates fold GEOMETRY. Neither
    catches an off-by-one in the JOIN -- features from row i+1 against the label
    for the trade entered at row i. That passes every audit in this file and
    produces a spectacular false positive. It is a named instance of the blind
    spot already in LEAK_AUDIT_KNOWN_LIMITATIONS: a defect uniform across every
    fold and every asset is caught by none of the three layers.

    The invariant assertions in add_execution_price and label_targets prove the
    join is correct today. They do not prove the pipeline would NOTICE if it
    were not -- correct-by-reading is the state the R2 ewm defect was in before
    it was found. This function supplies the missing half.

    Features are shifted by `shift` rows within (asset, epoch) while labels stay
    put. Shift -1 hands each row the NEXT bar's features -- the leaking
    direction -- so AUC must move decisively toward 1. Shift +1 is stale rather
    than leaking and should not improve anything. Both are recorded; only the
    leaking case is pass/fail.

    One early fold, one seed: this validates a DETECTOR, it is not a
    confirmatory measurement.
    """
    from sklearn.metrics import roc_auc_score
    model_params = dict(model_params or MODEL_PARAMS)
    fold_kwargs = fold_kwargs or {}
    rows = []
    base = add_execution_price(label_targets(featured, direction, m_by_asset,
                                             progress=False))
    folds = build_fold_schedule(featured, FIRST_TEST_START, **fold_kwargs)[:1]
    if not folds:
        return pd.DataFrame(rows)

    def _auc(frame):
        needed = list(FEATURE_COLS) + ["target", "next_open"]
        d = frame.dropna(subset=needed).copy()
        d["target"] = d["target"].astype(int)
        m = folds[0].masks(d)
        fit, inner, test = d[m["fit"]], d[m["inner"]], d[m["test"]]
        if len(fit) < 50 or len(inner) < 20 or len(test) < 5:
            return np.nan
        if (fit["target"].nunique() < 2 or inner["target"].nunique() < 2
                or test["target"].nunique() < 2):
            return np.nan
        model = _fit_one(fit[FEATURE_COLS], fit["target"],
                         inner[FEATURE_COLS], inner["target"], [],
                         model_params, DIAGNOSTIC_SEEDS[0])
        try:
            return float(roc_auc_score(
                test["target"], model.predict_proba(test[FEATURE_COLS])[:, 1]))
        except ValueError:
            return np.nan

    clean_auc = _auc(base)
    for shift in shifts:
        planted = base.copy()
        for f in FEATURE_COLS:
            planted[f] = (planted.groupby(["asset", "epoch"], sort=False)[f]
                                 .shift(shift))
        planted_auc = _auc(planted)
        leaking = shift < 0
        delta = (planted_auc - clean_auc
                 if np.isfinite(planted_auc) and np.isfinite(clean_auc) else np.nan)
        detected = bool(np.isfinite(delta) and delta > 0.05)
        rows.append({
            "shift_rows": shift,
            "direction_of_shift": ("LEAKING (next bar's features)" if leaking
                                   else "STALE (previous bar's features)"),
            "clean_auc": clean_auc, "planted_auc": planted_auc,
            "auc_delta": delta, "detected": detected, "is_passfail": leaking,
            "verdict": ("DETECTOR_OK" if (detected or not leaking)
                        else "DETECTOR_BLIND"),
        })
    return pd.DataFrame(rows)


NULL_TEST_FOLDS = 30
MIN_NULL_TEST_FOLDS = 20
NULL_TEST_SEED = 20260822


def run_null_and_canary(labelled, feature_cols, folds, direction, label="",
                        model_params=None):
    """S9 B4 -- shuffled-label null test plus a canary that proves it has power.

    B3 covers feature CONSTRUCTION. It cannot catch a leak in fold GEOMETRY --
    an off-by-one purge, an overlapping slice, a threshold chosen on the wrong
    rows. For that, destroy the signal and check the pipeline reports none. The
    canary (a feature that IS the label) proves the harness can detect leakage
    when present; without it, a PASS from the null arm means nothing.

    B4 FIX vs catboostv2.py L2130: the fold count there came from
    `len(frame) // (bars_per_day * n_folds)`, which is ROW-based -- a 3x longer
    pooled frame tripled the step and yielded a third of the folds, straight
    into INSUFFICIENT_POWER. Folds are now passed in directly, counted in
    union-days, and subsampled to NULL_TEST_FOLDS.
    """
    rng = np.random.default_rng(NULL_TEST_SEED)
    if len(folds) > NULL_TEST_FOLDS:
        step = max(1, len(folds) // NULL_TEST_FOLDS)
        folds = folds[::step][:NULL_TEST_FOLDS]

    shuffled = labelled.copy()
    valid = shuffled["target"].notna()
    shuffled.loc[valid, "target"] = rng.permutation(
        shuffled.loc[valid, "target"].to_numpy())

    canary = labelled.copy()
    canary["_canary_leak"] = canary["target"].astype(float)

    out = []
    for arm, frame, cols in (("null_shuffled", shuffled, list(feature_cols)),
                             ("canary_leaked", canary, list(feature_cols) + ["_canary_leak"])):
        res, _, _ = run_walkforward(
            frame, cols, folds, direction,
            label="B4_" + arm + "_" + str(label),
            seeds=(NULL_TEST_SEED,),
            model_params={**(model_params or MODEL_PARAMS), "iterations": 300})
        aucs = res["auc"].dropna().to_numpy() if len(res) else np.array([])
        if len(aucs) < 2:
            out.append({"arm": arm, "direction": direction, "scope": label,
                        "n_folds": len(aucs), "mean_auc": np.nan,
                        "t_vs_0.5": np.nan, "verdict": "INSUFFICIENT"})
            continue
        t = (aucs.mean() - 0.5) / (aucs.std(ddof=1) / np.sqrt(len(aucs)))
        if arm == "null_shuffled":
            # A null arm that could not have earned a PASS must not report one.
            if len(aucs) < MIN_NULL_TEST_FOLDS:
                verdict = "INSUFFICIENT_POWER"
            else:
                verdict = "PASS" if abs(t) < 3.0 else "LEAK_SUSPECTED"
        else:
            verdict = "PASS" if aucs.mean() > 0.90 else "DETECTOR_BLIND"
        out.append({"arm": arm, "direction": direction, "scope": label,
                    "n_folds": len(aucs), "mean_auc": float(aucs.mean()),
                    "t_vs_0.5": float(t), "verdict": verdict})
    return pd.DataFrame(out)


