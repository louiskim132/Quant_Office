def compute_epoch_id(series, max_gap_bars=GAP_TOLERANCE_BARS):
    """Epoch id from runs of missing values. Carried from R1 unchanged.

    G1: this detects epochs from NaN RUNS, which presupposes a frame already
    reindexed to a regular grid with gaps present as NaN rows. `assemble` now
    guarantees that. Before G1 the frame carried gaps as MISSING ROWS, so no NaN
    run ever existed, every asset collapsed to a single epoch, and the epoch
    machinery was dead code.
    """
    is_valid = series.notna()
    run_id = (is_valid != is_valid.shift()).cumsum()
    run_length = series.groupby(run_id).transform("size")
    is_long_gap_run = (~is_valid) & (run_length > max_gap_bars)
    is_run_end = (run_id != run_id.shift(-1))
    long_gap_ends = is_long_gap_run & is_run_end
    # R17b: .fillna(False) on an object-dtype boolean series is deprecated
    # and changes behaviour in pandas 3. Cast explicitly.
    epoch_id = (long_gap_ends.shift(1).astype("boolean")
                             .fillna(False).astype(bool).cumsum())
    return epoch_id.astype(np.int32)


def assign_epochs(frame, source_col="close", out_col="epoch"):
    """S2.4 -- epochs are computed PER ASSET. A gap in BTC must not re-warm
    XRP's windows."""
    out = frame.copy()
    out[out_col] = (out.groupby("asset", sort=False)[source_col]
                       .transform(lambda s: compute_epoch_id(s)))
    return out


def epoch_rolling(frame, col, window, min_periods, agg="mean", epoch_col="epoch"):
    """S2.4 -- every rolling call groups by (asset, epoch).

    With min_periods == window, any window overlapping a NaN gap returns NaN.
    That is the registered no-forward-fill behaviour, not a defect: a short gap
    inside an epoch nulls the statistics that would have spanned it.
    """
    grouped = frame.groupby(["asset", epoch_col], sort=False)[col]
    fns = {
        "mean": lambda s: s.rolling(window, min_periods=min_periods).mean(),
        "std": lambda s: s.rolling(window, min_periods=min_periods).std(),
        "sum": lambda s: s.rolling(window, min_periods=min_periods).sum(),
        "median": lambda s: s.rolling(window, min_periods=min_periods).median(),
        # R8: honours the caller's min_periods like every other branch. It
        # previously hard-coded min_periods=1 while accepting the argument, a
        # silent parameter mismatch in a widely used helper.
        "count": lambda s: s.rolling(window, min_periods=min_periods).count(),
    }
    if agg not in fns:
        raise ValueError("Unsupported agg: " + str(agg))
    return grouped.transform(fns[agg])


def observed_run_id(frame, col="close", epoch_col="epoch"):
    """R2 -- index of the contiguous observed/missing run each row belongs to.

    Within (asset, epoch), alternating runs of observed and missing bars get
    distinct ids. Grouping a recursive statistic by (asset, epoch, run) restarts
    its accumulator at every gap, however short -- which epoch grouping alone
    cannot do, since sub-tolerance gaps never split an epoch.
    """
    valid = frame[col].notna()
    return (valid.groupby([frame["asset"], frame[epoch_col]], sort=False)
                 .transform(lambda s: (s != s.shift()).cumsum())
                 .astype(np.int32))


def epoch_shift(frame, col, periods=1, epoch_col="epoch"):
    return frame.groupby(["asset", epoch_col], sort=False)[col].shift(periods)


def epoch_diff(frame, col, periods=1, epoch_col="epoch"):
    return frame.groupby(["asset", epoch_col], sort=False)[col].diff(periods)


def longest_stable_range(times, gap_limit=STABLE_GAP_LIMIT):
    """S2.2 -- longest contiguous run whose internal gaps never exceed
    gap_limit. Run independently per asset; ranges are NOT intersected, because
    assets legitimately start at different dates."""
    t = pd.Series(pd.to_datetime(times)).sort_values().reset_index(drop=True)
    if len(t) == 0:
        return None, None
    gaps = t.diff()
    break_at = np.flatnonzero((gaps > gap_limit).to_numpy())
    starts = np.concatenate([[0], break_at])
    ends = np.concatenate([break_at, [len(t)]])              # half-open
    best = int(np.argmax(ends - starts))
    return t.iloc[starts[best]], t.iloc[ends[best] - 1]


