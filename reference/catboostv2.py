def measured_spread(frame, spread_col=SPREAD_COL, ticks_col=SPREAD_TICKS_COL):
    """R17 -- the measured spread statistic for one slice.

    MEDIAN, not mean. `avg_spread_pct` is already a within-bar mean of top-of-
    book snapshots, so a mean across bars is a mean of means: a handful of
    dislocated bars (a listing gap, a flash move, a maintenance window) would
    set the constant that governs every cost in the run. The median is the
    typical quoted spread, which is what a taker actually crosses.

    Returns (median_pct, median_ticks, n_observed, coverage_fraction).
    """
    if spread_col not in frame.columns or len(frame) == 0:
        return np.nan, np.nan, 0, 0.0
    s = pd.to_numeric(frame[spread_col], errors="coerce")
    s = s[np.isfinite(s) & (s > 0)]
    ticks = (pd.to_numeric(frame[ticks_col], errors="coerce")
             if ticks_col in frame.columns else pd.Series(dtype=float))
    ticks = ticks[np.isfinite(ticks) & (ticks > 0)]
    coverage = float(len(s) / len(frame)) if len(frame) else 0.0
    if len(s) == 0:
        return np.nan, np.nan, 0, coverage
    return (float(s.median()),
            float(ticks.median()) if len(ticks) else np.nan,
            int(len(s)), coverage)


def derive_spreads(frame, assets=None, warmup_days=WARMUP_DAYS):
    """G4/R17 -- per-asset spread from MEASURED top-of-book, frozen warm-up.

    bookTicker covers 2020 through 2024-03 and the warm-up prefix is 2020-2021,
    so the constant that governs the run is fully measured. The post-2024
    bookTicker gap never touches it.

    THERE IS NO FALLBACK. Every previous version substituted SPREAD_CAP_PCT
    when the estimate was unavailable, which defeated `round_trip_cost`'s
    provenance guard: an underived cost reached the gate wearing a derivation's
    clothes. That is exactly how the first M1 run charged a 20bp round trip
    against a ~7bp reality and kept going. Floor, cap, tick and coverage
    violations all RAISE, with the observed value named.

    R6: the universe defaults to what the frame actually contains, so a partial
    run cannot silently reintroduce a dropped asset.
    """
    if assets is None:
        assets = tuple(frame["asset"].unique())

    rows, prov, failures = {}, [], []
    for asset in assets:
        wu = warmup_slice(frame, asset, warmup_days=warmup_days)
        wu_observed = wu.dropna(subset=["close"])
        med_pct, med_ticks, n_obs, coverage = measured_spread(wu_observed)

        reason = ""
        if not np.isfinite(med_pct):
            reason = ("no measured spread in the warm-up prefix -- bookTicker "
                      "missing for this asset/period")
        elif coverage < SPREAD_MIN_COVERAGE:
            reason = ("warm-up spread coverage " + format(coverage, ".4f")
                      + " below SPREAD_MIN_COVERAGE "
                      + format(SPREAD_MIN_COVERAGE, ".2f"))
        elif med_pct < SPREAD_FLOOR_PCT:
            reason = ("measured spread " + format(med_pct, ".8f")
                      + " below SPREAD_FLOOR_PCT -- suspect a wrong column")
        elif med_pct > SPREAD_CAP_PCT:
            reason = ("measured spread " + format(med_pct, ".8f")
                      + " above SPREAD_CAP_PCT -- suspect bad data")
        elif np.isfinite(med_ticks) and med_ticks < SPREAD_MIN_TICKS:
            # A quoted spread narrower than one tick is impossible. This
            # separates "wrong tick size or wrong column" from "very liquid",
            # which the percentage bounds cannot do.
            reason = ("measured spread " + format(med_ticks, ".4f")
                      + " ticks, below one tick -- suspect a tick-size or "
                        "column error")

        if reason:
            failures.append(asset + ": " + reason)
        else:
            rows[asset] = med_pct

        prov.append({
            "asset": asset,
            "estimator": "measured top-of-book median (bookTicker avg_spread_pct)",
            "spread_pct_used": rows.get(asset, np.nan),
            "spread_ticks_median": med_ticks,
            "warmup_coverage": round(coverage, 6),
            "n_bars_with_spread": n_obs,
            "warmup_days": warmup_days,
            "warmup_start": wu["time"].min() if len(wu) else pd.NaT,
            "warmup_end": wu["time"].max() if len(wu) else pd.NaT,
            "superseded_constant": SPREAD_PCT_SUPERSEDED.get(asset, np.nan),
            "fee_per_txn": FEE_PER_TXN,
            "round_trip_cost": (2 * FEE_PER_TXN
                                + 2 * SLIPPAGE_SPREAD_FRACTION * rows[asset]
                                if asset in rows else np.nan),
            "failure_reason": reason,
            # R17 known limitation: the quoted top-of-book spread assumes the
            # order fills at the touch. For small notional on liquid majors that
            # holds; it UNDERSTATES cost for size that would sweep levels. Depth
            # is not modelled -- recorded rather than approximated.
            "known_limitation": "top-of-book only; understates cost for size "
                                "that sweeps multiple levels",
        })

    save_section_csv(pd.DataFrame(prov), "s3_spread_provenance")
    save_section_csv(CS_WITHDRAWAL_EVIDENCE, "s3_cs_withdrawal_evidence")

    if failures:
        raise RuntimeError(
            "G4/R17: measured spread unavailable or out of bounds for "
            + str(len(failures)) + " asset(s). No fallback exists -- a clamped "
            "constant is the underived guess G4 was written to remove.\n  "
            + "\n  ".join(failures)
            + "\nSee s3_spread_provenance for the full table.")

    set_spreads(rows, source="measured top-of-book median, frozen warm-up prefix")

    # R3/R17 -- per-year diagnostic. Never used; recorded so drift in the frozen
    # constant is legible. Under CS this table reported volatility by year and
    # was meaningless. Measured, it reports real spread compression, which is a
    # finding: a frozen 2020 constant OVERSTATES later-year cost. Conservative
    # in direction, and now legible rather than latent. bookTicker ends 2024-03,
    # so later years report NaN with their coverage alongside.
    year_rows = []
    for asset in assets:
        sub = frame[frame["asset"] == asset]
        for year, grp in sub.groupby(sub["time"].dt.year, sort=True):
            med_pct, med_ticks, n_obs, coverage = measured_spread(
                grp.dropna(subset=["close"]))
            year_rows.append({
                "asset": asset, "year": int(year),
                "spread_pct_measured_DIAGNOSTIC_ONLY": med_pct,
                "spread_ticks_median": med_ticks,
                "spread_pct_in_use_frozen": rows[asset],
                "ratio_year_over_frozen": (med_pct / rows[asset]
                                           if np.isfinite(med_pct) and rows[asset]
                                           else np.nan),
                "coverage": round(coverage, 6),
                "n_bars_with_spread": n_obs,
                "note": ("diagnostic only; the frozen warm-up value governs "
                         "(S3.2 precedence). bookTicker ends 2024-03"),
            })
    save_section_csv(pd.DataFrame(year_rows), "s3_spread_drift_by_year")
    return rows

