def apply_cost_model(direction, next_open, exit_price, asset):
    """S10 -- size-independent net return, taker fees and spread only.

    The funding term is GONE, not zeroed: S0 deletes the funding machinery
    outright. `asset` is required because S10 makes ROUND_TRIP_COST per asset.
    """
    next_open = np.asarray(next_open, dtype=float)
    exit_price = np.asarray(exit_price, dtype=float)
    if direction == "long":
        gross = (exit_price - next_open) / next_open
    else:
        gross = (next_open - exit_price) / next_open
    if isinstance(asset, str):
        cost = round_trip_cost(asset)
    else:
        cost = np.asarray([round_trip_cost(a) for a in asset], dtype=float)
    return gross - cost


def newey_west_tstat(x, lag=NW_LAG):
    """t-statistic for the mean of `x` with a Bartlett-kernel HAC correction.

    S6.2: 2-day blocking attenuates the spill of trades across block boundaries
    but does not remove it -- the residual scales as
    mean_holding / block_length. NW handles the remainder exactly rather than by
    attenuation, which is why S6.2 registers both plus the autocorrelation
    report, rather than a choice among them.
    """
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    n = len(x)
    if n < 2:
        return np.nan, np.nan, n
    mean = x.mean()
    dev = x - mean
    gamma0 = float(dev @ dev) / n
    var = gamma0
    for l in range(1, min(lag, n - 1) + 1):
        gamma_l = float(dev[l:] @ dev[:-l]) / n
        var += 2.0 * (1.0 - l / (lag + 1.0)) * gamma_l
    if var <= 0:
        return np.nan, mean, n
    return float(mean / np.sqrt(var / n)), float(mean), n


def block_series(trades, block_days=BLOCK_DAYS, time_col="time",
                 value_col="net_return"):
    """S6.2 -- one asset's daily mean net return, aggregated into
    non-overlapping `block_days` blocks.

    Confirmatory cells are per (direction, asset) and never pool a significance
    claim across assets, so contemporaneous cross-asset correlation cannot enter
    this statistic. The cross-asset average is a diagnostic pooled summary only
    (see `pooled_diagnostic_block_series`).

    M5 (ratified): a block is the MEAN OF ITS DAILY MEANS, equal-weighting the
    two days regardless of trade counts. This matches the registered S6.2
    wording -- "daily mean net return -> blocks". Do not "correct" it to
    trade-weighting.
    """
    d = trades.dropna(subset=[value_col]).copy()
    if len(d) == 0:
        return pd.DataFrame(columns=["block", "block_start", "n_trades", value_col])
    d[time_col] = pd.to_datetime(d[time_col])
    d["_day"] = d[time_col].dt.floor("D")
    daily = d.groupby("_day", as_index=False).agg(
        **{value_col: (value_col, "mean"), "n_trades": (value_col, "size")})
    origin = daily["_day"].min()
    daily["block"] = ((daily["_day"] - origin).dt.days // block_days).astype(int)
    return daily.groupby("block", as_index=False).agg(
        block_start=("_day", "min"),
        n_trades=("n_trades", "sum"),
        **{value_col: (value_col, "mean")})


def block_autocorr(x, lag=1):
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if len(x) <= lag + 1:
        return np.nan
    dev = x - x.mean()
    denom = float(dev @ dev)
    if denom <= 0:
        return np.nan
    return float(dev[lag:] @ dev[:-lag]) / denom


def confirmatory_cell(trades, asset, direction, family_size,
                      block_days=BLOCK_DAYS, lag=NW_LAG):
    """S6.2 + S10 -- one confirmatory cell's registered statistic.

    Reports the trio S6.2 requires: the NW-corrected block t, the block-series
    autocorrelation (so the correction's necessity is visible rather than
    assumed), and the non-empty block count the reporting floor gates on.
    """
    blocks = block_series(trades, block_days=block_days)
    vals = blocks["net_return"].to_numpy(dtype=float) if len(blocks) else np.array([])
    t_nw, mean_block, n_blocks = newey_west_tstat(vals, lag=lag)
    t_thresh = BH_T_BY_FAMILY.get(family_size, np.nan)
    mean_trade = float(trades["net_return"].mean()) if len(trades) else np.nan
    win_rate = (float(trades["target"].mean())
                if "target" in trades and len(trades) else np.nan)
    rtc = round_trip_cost(asset)
    return {
        "asset": asset, "direction": direction,
        "n_trades": int(len(trades)),
        "n_blocks_nonempty": int(n_blocks),
        "block_days": block_days, "nw_lag": lag,
        "mean_net_return_per_trade": mean_trade,
        "mean_net_return_per_block": mean_block,
        "win_rate": win_rate,
        "breakeven_win_rate": round(BREAKEVEN_WIN_RATE, 4),
        "t_block_nw": t_nw,
        "block_autocorr_lag1": block_autocorr(vals, 1),
        "bh_t_threshold": t_thresh,
        # S10: the criterion is net > 0. M1 v1's "net > ROUND_TRIP_COST"
        # double-charged, since apply_cost_model has already subtracted the
        # round trip. The margin is separate, named, and outside the test.
        "passes_significance": bool(np.isfinite(t_nw) and np.isfinite(t_thresh)
                                    and t_nw > t_thresh),
        "passes_net_positive": bool(np.isfinite(mean_trade) and mean_trade > 0),
        "passes_margin_condition": bool(np.isfinite(mean_trade)
                                        and mean_trade > 0.5 * rtc),
        "suppressed_below_min_blocks": bool(n_blocks < MIN_REPORTABLE_BLOCKS),
    }


def pooled_diagnostic_block_series(trades_by_asset, block_days=BLOCK_DAYS):
    """S6.2 -- the cross-asset average, a DIAGNOSTIC pooled summary only.

    Assets averaged within each fold-day, then blocked. This absorbs
    contemporaneous cross-asset correlation exactly, with no rho-bar and no
    separability assumption -- but it is never a confirmatory statistic, because
    S10's family is per (direction, asset) and pools no significance claim.
    """
    frames = []
    for asset, trades in trades_by_asset.items():
        d = trades.dropna(subset=["net_return"]).copy()
        if len(d) == 0:
            continue
        d["time"] = pd.to_datetime(d["time"])
        d["_day"] = d["time"].dt.floor("D")
        frames.append(d.groupby("_day", as_index=False)["net_return"].mean()
                       .assign(asset=asset))
    if not frames:
        return pd.DataFrame(columns=["block", "block_start", "n_assets", "net_return"])
    daily = pd.concat(frames, ignore_index=True)
    cross = daily.groupby("_day", as_index=False).agg(
        net_return=("net_return", "mean"), n_assets=("asset", "nunique"))
    origin = cross["_day"].min()
    cross["block"] = ((cross["_day"] - origin).dt.days // block_days).astype(int)
    return cross.groupby("block", as_index=False).agg(
        block_start=("_day", "min"), n_assets=("n_assets", "max"),
        net_return=("net_return", "mean"))


def mean_pairwise_correlation(trades_by_asset):
    """S9 B7 -- rho-bar, the average pairwise correlation of contemporaneous
    per-day net returns across assets. Diagnostic only: it informs
    interpretation and never enters a standard error.

    S6.2 note: the confirmatory cells are positively correlated across assets.
    BH remains valid under positive regression dependence, so that correlation
    makes it conservative rather than invalid. Nobody should "correct" for it.
    """
    series = {}
    for asset, trades in trades_by_asset.items():
        d = trades.dropna(subset=["net_return"]).copy()
        if len(d) == 0:
            continue
        d["time"] = pd.to_datetime(d["time"])
        series[asset] = d.groupby(d["time"].dt.floor("D"))["net_return"].mean()
    if len(series) < 2:
        return np.nan
    wide = pd.DataFrame(series).dropna()
    if len(wide) < 3:
        return np.nan
    corr = wide.corr().to_numpy()
    vals = corr[np.triu_indices_from(corr, k=1)]
    vals = vals[np.isfinite(vals)]
    return float(vals.mean()) if len(vals) else np.nan

