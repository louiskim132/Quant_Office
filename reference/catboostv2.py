def cost_feasible_rate(frame, asset, m, tp_multiplier=TP_MULTIPLIER):
    """S3.1 -- fraction of bars whose TP distance clears COST_MULTIPLE round
    trips. Monotone increasing in m, which is what makes the crossing search
    valid. Vectorised: no forward scan needed."""
    sub = frame[frame["asset"] == asset]
    tp_pct = tp_multiplier * m * sub["atr14_lagged"] / sub["close"]
    tp_pct = tp_pct.replace([np.inf, -np.inf], np.nan).dropna()
    if len(tp_pct) == 0:
        return np.nan
    return float((tp_pct >= cost_floor_fractional(asset)).mean())


def horizon_binding_rate(frame, asset, m, tp_multiplier=TP_MULTIPLIER,
                         max_horizon=MAX_HORIZON, entry_stride=GATE_ENTRY_STRIDE):
    """S3.1 -- fraction of entries where MAX_HORIZON binds before either barrier.

    Monotone increasing in m. D1 (ratified): the gate takes the MAX across
    directions. The long band is [entry - m*ATR, entry + 1.2m*ATR] and the short
    band is its mirror, so the rates differ; both models are trained, so
    short-side attrition is real attrition. Both rates are reported.

    Unobserved paths (epoch end, gap rows) are excluded from the denominator.
    """
    sub = frame[frame["asset"] == asset]
    rates = {}
    for direction in ("long", "short"):
        fp = first_passage(sub, direction, m, tp_multiplier, max_horizon,
                           entry_stride=entry_stride)
        scanned = fp[~fp["status"].isin(UNOBSERVED_STATUSES)]
        rates[direction] = (float((scanned["status"] == RES_HORIZON).mean())
                            if len(scanned) else np.nan)
        # M2: the actual scanned count, not len(sub) // entry_stride, which
        # ignored NaN-sl_dist skips, gap rows and epoch boundaries.
        rates["n_scanned_" + direction] = int(len(scanned))
    both = [rates[d] for d in ("long", "short") if np.isfinite(rates[d])]
    rates["max"] = max(both) if both else np.nan
    return rates


def _bisect_monotone(fn, target, bracket, tol, want="first_at_or_above"):
    """Smallest (or largest) m satisfying a monotone-increasing predicate.

    S3.1 registers a crossing-point search rather than a grid: both rate curves
    are monotone in m, and a coarse grid can report "no admissible multiplier"
    when one exists between grid points.

    M3: NaN handling is directional (`lo = mid` suits first_at_or_above and
    would bias last_below upward). In practice NaN arises only on empty frames,
    which the endpoint checks below already catch -- hence the assertion rather
    than new branch logic.
    """
    lo, hi = bracket
    f_lo, f_hi = fn(lo), fn(hi)
    assert np.isfinite(f_lo) or np.isfinite(f_hi), (
        "S3.1: both bracket endpoints evaluate to NaN -- the frame carries no "
        "usable bars, so the crossing search is undefined")
    if want == "first_at_or_above":
        if np.isfinite(f_lo) and f_lo >= target:
            return lo
        if not (np.isfinite(f_hi) and f_hi >= target):
            return np.nan                       # never feasible in the bracket
    else:                                        # last_below
        if np.isfinite(f_lo) and f_lo >= target:
            return np.nan                       # already violating at the floor
        if np.isfinite(f_hi) and f_hi < target:
            return hi                           # never violates in the bracket
    while hi - lo > tol:
        mid = 0.5 * (lo + hi)
        f_mid = fn(mid)
        if not np.isfinite(f_mid):
            lo = mid
            continue
        if f_mid >= target:
            hi = mid
        else:
            lo = mid
    return hi if want == "first_at_or_above" else lo


def admissible_window(frame, asset, entry_stride=GATE_ENTRY_STRIDE):
    """S3.1 -- [m_min, m_max] for one asset. Drop the asset iff m_min > m_max."""
    m_min = _bisect_monotone(
        lambda m: cost_feasible_rate(frame, asset, m),
        GATE_FEASIBLE_RATE_FLOOR, GATE_M_BRACKET, GATE_M_TOL,
        want="first_at_or_above")
    m_max = _bisect_monotone(
        lambda m: horizon_binding_rate(frame, asset, m, entry_stride=entry_stride)["max"],
        GATE_BINDING_RATE_CEILING, GATE_M_BRACKET, GATE_M_TOL,
        want="last_below")
    return m_min, m_max


# D3 (ratified): per-year windows are computed on year-sliced frames, so entries
# in the final MAX_HORIZON bars of each year resolve as epoch-end and drop out
# of the denominator -- roughly 96 bars, about 0.3% of a year. Immaterial and
# unbiased across m, recorded here and in the per-year CSV.
PER_YEAR_LIMITATION = ("year-sliced scan: the final ~96 bars of each year "
                       "resolve as epoch-end and are excluded (~0.3%, unbiased in m)")

# R7: the same edge effect on the evaluation-window slice used by S3.3.
EVAL_WINDOW_LIMITATION = ("eval-window slice: the final ~96 bars resolve as "
                          "epoch-end and leave the denominator (~0.02% over "
                          "1,460 days; same effect as PER_YEAR_LIMITATION)")


def run_gate(frame, assets=None, entry_stride=GATE_ENTRY_STRIDE):
    """S3 -- the blocking gate.

    Emits, per asset: pooled and per-year admissible windows, the frozen warm-up
    m with its rates AT that m (G2), the S3.2 later-window diagnostic, and the
    survivor verdict that fixes the confirmatory family size.

    R6: the universe defaults to what the frame contains, not module-level
    ASSETS, so a partial run cannot silently reintroduce a dropped asset.
    """
    if assets is None:
        assets = tuple(frame["asset"].unique())
    pooled_rows, year_rows, m_rows = [], [], []
    survivors, m_by_asset = [], {}

    for asset in assets:
        # R10 Option A: the survivor decision comes from the frozen warm-up
        # prefix. The full-sample window is still computed and reported, as a
        # drift diagnostic only.
        wu = warmup_slice(frame, asset)
        wu_min, wu_max = admissible_window(wu, asset, entry_stride)
        m_min, m_max = admissible_window(frame, asset, entry_stride)
        if SURVIVORSHIP_SOURCE == "warmup":
            survives = bool(np.isfinite(wu_min) and np.isfinite(wu_max)
                            and wu_min <= wu_max)
        elif SURVIVORSHIP_SOURCE == "full_sample":
            survives = bool(np.isfinite(m_min) and np.isfinite(m_max)
                            and m_min <= m_max)
        else:
            raise ValueError("SURVIVORSHIP_SOURCE must be 'warmup' or "
                             "'full_sample', got " + repr(SURVIVORSHIP_SOURCE))
        # Under Option A the reported rates must correspond to the multiplier
        # actually in use, which comes from the warm-up window. Probing at the
        # full-sample m_min would report rates for a multiplier no longer used
        # anywhere. Cosmetic -- these feed only the reported binding rates and
        # nothing decides on them -- but an internally inconsistent diagnostic
        # table is how a later reader draws the wrong conclusion.
        probe_source = wu_min if SURVIVORSHIP_SOURCE == "warmup" else m_min
        probe = probe_source if survives else GATE_M_BRACKET[0]
        binding = horizon_binding_rate(frame, asset, probe, entry_stride=entry_stride)
        pooled_rows.append({
            "asset": asset, "m_min": m_min, "m_max": m_max,
            "window_nonempty": survives,
            "round_trip_cost": round_trip_cost(asset),
            "cost_floor_fractional": cost_floor_fractional(asset),
            "probe_m": probe,
            "binding_rate_long_at_probe": binding["long"],
            "binding_rate_short_at_probe": binding["short"],
            "n_scanned_long": binding["n_scanned_long"],
            "feasible_rate_floor": GATE_FEASIBLE_RATE_FLOOR,
            "binding_rate_ceiling": GATE_BINDING_RATE_CEILING,
            "survivorship_source": SURVIVORSHIP_SOURCE,
            "warmup_m_min": wu_min, "warmup_m_max": wu_max,
            "full_sample_window_is_diagnostic": SURVIVORSHIP_SOURCE == "warmup",
            "verdict": "SURVIVES" if survives else "DROPPED",
        })
        if not survives:
            continue
        survivors.append(asset)

        # S3.2 -- m from the frozen warm-up prefix, MIDPOINT of the window.
        # Midpoint, not m_min: the lower edge is where vol compression evicts
        # the barrier, and anchoring there would defeat the per-year drift
        # detection the table below exists to provide. R10: wu / wu_min / wu_max
        # are already computed above for the survivor decision -- one call, not
        # two.
        m_asset = (0.5 * (wu_min + wu_max)
                   if np.isfinite(wu_min) and np.isfinite(wu_max) else np.nan)
        m_by_asset[asset] = m_asset

        # S3.2 -- the later-window diagnostic. XRP's frozen prefix contains the
        # December 2020 SEC action, the window S8 names as unrepresentative.
        # Accepted, because the prefix is never tested on: a bad constant costs
        # efficiency, not validity. Reported so the exposure stays legible.
        later = warmup_slice(frame, asset, start_offset_days=LATER_WINDOW_OFFSET_DAYS)
        if len(later):
            l_min, l_max = admissible_window(later, asset, entry_stride)
            m_later = (0.5 * (l_min + l_max)
                       if np.isfinite(l_min) and np.isfinite(l_max) else np.nan)
        else:
            l_min = l_max = m_later = np.nan

        # G2 -- rates AT the frozen m, which is what the S3.2 escape valve is
        # stated against. The pooled block above probes at m_min, which is a
        # different quantity and cannot stand in for this.
        if np.isfinite(m_asset):
            at_m = horizon_binding_rate(frame, asset, m_asset, entry_stride=entry_stride)
            feas_at_m = cost_feasible_rate(frame, asset, m_asset)
        else:
            at_m = {"long": np.nan, "short": np.nan, "max": np.nan}
            feas_at_m = np.nan

        # S3.2 precedence: a frozen m outside the full-sample window is RECORDED
        # as a drift finding and M1 proceeds with the frozen m. It is not a
        # re-derivation trigger. The escape valve is the realized binding rate,
        # checked after labeling in `audit_realized_binding`, which is a stop.
        in_full = bool(np.isfinite(m_asset) and m_min <= m_asset <= m_max)
        m_rows.append({
            "asset": asset,
            "m_asset_frozen": m_asset,
            "warmup_m_min": wu_min, "warmup_m_max": wu_max,
            "warmup_days": WARMUP_DAYS,
            "warmup_start": wu["time"].min() if len(wu) else pd.NaT,
            "warmup_end": wu["time"].max() if len(wu) else pd.NaT,
            "full_sample_m_min": m_min, "full_sample_m_max": m_max,
            "frozen_m_inside_full_window": in_full,
            "drift_finding": "" if in_full else
                "frozen m outside full-sample window; proceeding with frozen m per S3.2",
            "cost_feasible_rate_at_frozen_m": feas_at_m,
            "binding_rate_long_at_frozen_m": at_m["long"],
            "binding_rate_short_at_frozen_m": at_m["short"],
            "binding_rate_max_at_frozen_m": at_m["max"],
            "binding_ceiling": GATE_BINDING_RATE_CEILING,
            # R4: operator ergonomics, NOT a rule change. The registered stop is
            # the REALIZED rate at stride 1, checked by audit_realized_binding
            # after full labeling. This is a stride-4 PROJECTION of the same
            # quantity, surfaced now so an operator does not spend hours
            # labelling before learning the run will stop. The column name says
            # "projected" so the projection can never quietly stand in for the
            # registered stop.
            "projected_audit_verdict": (
                "PROJECTED_FAIL" if (np.isfinite(at_m["max"])
                                     and at_m["max"] > GATE_BINDING_RATE_CEILING)
                else "PROJECTED_PASS"),
            "m_later_window_DIAGNOSTIC_ONLY": m_later,
            "later_window_m_min": l_min, "later_window_m_max": l_max,
            "derivation": "midpoint[m_min, m_max] on the frozen warm-up prefix",
        })

        # S3.1 -- per-year windows, distinguishing "the gate passes" from
        # "a single fixed m is defensible for this sample".
        sub = frame[frame["asset"] == asset]
        for year, grp in sub.groupby(sub["time"].dt.year, sort=True):
            y_min, y_max = admissible_window(grp, asset, entry_stride)
            y_at_m = (horizon_binding_rate(grp, asset, m_asset, entry_stride=entry_stride)["max"]
                      if np.isfinite(m_asset) else np.nan)
            year_rows.append({
                "asset": asset, "year": int(year), "n_bars": len(grp),
                "m_min": y_min, "m_max": y_max,
                "window_nonempty": bool(np.isfinite(y_min) and np.isfinite(y_max)
                                        and y_min <= y_max),
                "frozen_m_inside_year_window": bool(
                    np.isfinite(m_asset) and np.isfinite(y_min) and np.isfinite(y_max)
                    and y_min <= m_asset <= y_max),
                "binding_rate_max_at_frozen_m": y_at_m,
                "median_atr14_pct": float((grp["atr14_lagged"] / grp["close"]).median()),
                "known_limitation": PER_YEAR_LIMITATION,
            })

    save_section_csv(pd.DataFrame(pooled_rows), "s3_admissible_window_pooled")
    save_section_csv(pd.DataFrame(year_rows), "s3_admissible_window_by_year")
    m_df = pd.DataFrame(m_rows)
    save_section_csv(m_df, "s3_m_derivation")

    # R4: surface the projection prominently rather than burying it in a CSV.
    if len(m_df):
        projected_fail = m_df[m_df["projected_audit_verdict"] == "PROJECTED_FAIL"]
        if len(projected_fail):
            print("\n*** R4 PROJECTED_FAIL -- stride-4 binding above the ceiling "
                  "at the frozen m for: "
                  + ", ".join(projected_fail["asset"].tolist())
                  + "\n    This is a PROJECTION, not the registered stop. The stop "
                  "is the realized stride-1 rate checked after labeling.\n")

    family_size = 2 * len(survivors)
    verdict = {
        "n_survivors": len(survivors),
        "survivors": ",".join(survivors),
        "terminated": len(survivors) < 2,
        "confirmatory_family_size": family_size if len(survivors) >= 2 else np.nan,
        "bh_t_threshold": BH_T_BY_FAMILY.get(family_size, np.nan),
        "note": ("M1 TERMINATED: fewer than two surviving assets; no single-asset "
                 "run under the M1 label"
                 if len(survivors) < 2 else
                 "family size fixed here, before the walk-forward; the gate "
                 "consults no outcome data, which is what makes this legitimate"),
    }
    save_section_csv(pd.DataFrame([verdict]), "s3_gate_verdict")
    return survivors, m_by_asset, verdict


def audit_realized_binding(labelled_by_direction, m_by_asset,
                           ceiling=GATE_BINDING_RATE_CEILING):
    """G2 -- the S3.2 escape valve, implemented as a STOP.

    "Realized horizon_binding_rate > 0.20 on the actual sample is an audit
    failure and a stop -- not a re-derivation trigger." Raises rather than
    warning: a printed warning is not a stop.
    """
    rows = []
    for direction, labelled in labelled_by_direction.items():
        rb = realized_binding_rate(labelled)
        rb["direction"] = direction
        rb["m_asset_frozen"] = rb["asset"].map(m_by_asset)
        rb["ceiling"] = ceiling
        rb["verdict"] = np.where(
            rb["realized_binding_rate"] > ceiling, "AUDIT_FAIL", "PASS")
        rows.append(rb)
    out = pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()
    save_section_csv(out, "s3_realized_binding_audit")
    failed = out[out["verdict"] == "AUDIT_FAIL"] if len(out) else out
    if len(failed):
        raise AssertionError(
            "S3.2 AUDIT FAILURE -- realized horizon binding above "
            + str(ceiling) + " at the frozen m:\n"
            + failed[["asset", "direction", "m_asset_frozen",
                      "realized_binding_rate"]].to_string(index=False)
            + "\nThis is a registered STOP, not a re-derivation trigger.")
    return out


def win_rate_for_sharpe(s, tp_multiplier=TP_MULTIPLIER):
    """Invert per-trade Sharpe to win rate under a fixed R:R.

    With outcomes +tp and -1: mean = (1+tp)p - 1, sd = (1+tp)sqrt(p(1-p)), so
    S = mean/sd, a quadratic in p.
    """
    if not np.isfinite(s):
        return np.nan
    k = 1.0 + tp_multiplier
    a = k * k * (1.0 + s * s)
    b = -(2.0 * k + s * s * k * k)
    c = 1.0
    disc = b * b - 4 * a * c
    if disc < 0:
        return np.nan
    # D4 (ratified): squaring introduces the root of the sign-flipped equation.
    # Select on the residual of the ORIGINAL equation rather than on
    # sign(k*p - 1), which is numerically undefined as s -> 0, where the true
    # root sits exactly at the breakeven rate 1/k.
    best, best_residual = np.nan, np.inf
    for root in ((-b + np.sqrt(disc)) / (2 * a), (-b - np.sqrt(disc)) / (2 * a)):
        if not (0.0 < root < 1.0):
            continue
        residual = abs((k * root - 1.0) - s * k * np.sqrt(root * (1.0 - root)))
        if residual < best_residual:
            best, best_residual = float(root), residual
    return best


def power_projection(frame, m_by_asset, survivors, t_k,
                     eval_start=FIRST_TEST_START, eval_end=HOLDOUT_START,
                     pass_rates=(1.0, 0.25, 0.10, 0.03),
                     block_days=BLOCK_DAYS, entry_stride=GATE_ENTRY_STRIDE):
    """S3.3 -- power projection derived from the S6.2 BLOCK estimator.

        B_total  = evaluation-window days / block_days
        M_raw    = mean candidate signals per block
        M_cap    = block_bars / mean_holding_bars
        M_eff(f) = min(f * M_raw, M_cap)
        B_ne(f)  = expected blocks with at least one trade
        S_req(f) = t_k / sqrt(B_ne(f) * M_eff(f))
        p_req(f) : solve 2.2p - 1 = S_req * 2.2 * sqrt(p(1-p))

    Informational, never a kill rule: the pass rate f is model-dependent and
    unknowable before the model exists. The kill conditions are S3.1 and S3.4.

    G3 (a): both directions. The confirmatory cells are per (direction, asset)
    and the short-over-long label asymmetry is an established structural
    property, so a long-only projection understates what the short cells need.

    G3 (b): B_total comes from the S8 EVALUATION window, passed in explicitly.
    Blocks exist only where test slices exist. Deriving it from the asset's full
    data span counted 2020-2021 -- which is training-only warm-up -- inflating
    B_total by roughly 50% and understating S_req by roughly 18%, both in the
    optimistic direction.
    """
    eval_days = max(1, (pd.Timestamp(eval_end) - pd.Timestamp(eval_start)).days)
    b_total = eval_days / block_days

    rows = []
    for asset in survivors:
        m = m_by_asset.get(asset)
        if m is None or not np.isfinite(m):
            continue
        sub = frame[(frame["asset"] == asset)
                    & (frame["time"] >= eval_start) & (frame["time"] < eval_end)]
        if len(sub) == 0:
            continue
        for direction in ("long", "short"):
            fp = first_passage(sub, direction, m, entry_stride=entry_stride)
            resolved = fp[fp["status"].isin([RES_TP, RES_SL])]
            if len(resolved) == 0:
                continue

            tp_pct = TP_MULTIPLIER * resolved["sl_dist"] / resolved["close"]
            feasible = resolved[(tp_pct >= cost_floor_fractional(asset)).to_numpy()]
            mean_holding = float(resolved["bars_to_resolution"].mean())

            # M_raw counts feasible candidates among RESOLVED entries only. That
            # is deliberate and correct: a horizon-bound entry produces no label
            # and therefore no trade, so it is not a candidate. Stated because
            # it reads as a bug until the reason is given.
            m_raw = (len(feasible) * entry_stride) / b_total
            m_cap = (block_days * BARS_PER_DAY) / max(1.0, mean_holding)

            for f in pass_rates:
                m_eff = min(f * m_raw, m_cap)
                # Independent-arrival approximation for the non-empty block
                # count; arrivals cluster, so this is an approximation and is
                # labelled as one.
                b_ne = b_total * (1.0 - (1.0 - f) ** max(1.0, m_raw))
                denom = b_ne * m_eff
                s_req = t_k / np.sqrt(denom) if denom > 0 else np.nan
                rows.append({
                    "asset": asset, "direction": direction, "pass_rate_f": f,
                    "eval_start": eval_start, "eval_end": eval_end,
                    "eval_days": eval_days,
                    "B_total": round(b_total, 1), "B_ne": round(b_ne, 1),
                    "M_raw": round(m_raw, 2), "M_cap": round(m_cap, 2),
                    "M_eff": round(m_eff, 2),
                    "mean_holding_bars": round(mean_holding, 2),
                    "t_k": t_k,
                    "required_per_trade_sharpe": (round(s_req, 4)
                                                  if np.isfinite(s_req) else np.nan),
                    "required_win_rate": (round(win_rate_for_sharpe(s_req), 4)
                                          if np.isfinite(s_req) else np.nan),
                    "breakeven_win_rate": round(BREAKEVEN_WIN_RATE, 4),
                    # R7: the eval-window slice inherits D3's end-of-window
                    # truncation. Immaterial over 1,460 days, flagged with the
                    # same column the per-year table carries so the two stay
                    # consistent.
                    "known_limitation": EVAL_WINDOW_LIMITATION,
                })

    out = pd.DataFrame(rows)
    save_section_csv(out, "s3_power_projection")
    return out

