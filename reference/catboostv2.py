def summarise_permutation(perm_by_fold):
    """S7 -- aggregate per-fold permutation AUC drops into a per-feature verdict.

    Folds are the clustering unit, matching catboostv2.py's summarise_fold_statistic
    convention: intraday rows within a fold share a regime and none of them enter
    this t-stat individually. BH is applied within each direction, because the
    feature family is tested once per direction.
    """
    from scipy import stats as sps
    rows = []
    for (direction, feature), grp in perm_by_fold.groupby(["direction", "feature"]):
        vals = grp["auc_drop"].to_numpy(dtype=float)
        vals = vals[np.isfinite(vals)]
        n = len(vals)
        if n == 0:
            continue
        mean = float(vals.mean())
        std = float(vals.std(ddof=1)) if n > 1 else np.nan
        t = mean / (std / np.sqrt(n)) if (n > 1 and std > 0) else np.nan
        rows.append({
            "direction": direction, "feature": feature, "n_folds": n,
            "mean_auc_drop": mean, "std_auc_drop": std, "t_stat": t,
            "p_value": (float(2 * sps.t.sf(abs(t), df=n - 1))
                        if np.isfinite(t) else np.nan),
            "pct_folds_positive": float(np.mean(vals > 0)),
        })
    out = pd.DataFrame(rows)
    if len(out):
        out["p_value_bh"] = np.concatenate([
            bh_adjust(g["p_value"].to_numpy())
            for _, g in out.groupby("direction", sort=False)])
        out["significant_bh_05"] = out["p_value_bh"] < 0.05
        out = out.sort_values(["direction", "t_stat"], ascending=[True, False])
    return out


def build_confirmatory_table(oof_by_direction, survivors, family_size):
    """S10 -- the confirmatory family: 2 directions x surviving assets, primary
    geometry, Arm P, seed-ensembled. Each cell's statistic is the S6.2 per-asset
    block estimator.

    Family size was fixed by the S3 result BEFORE the walk-forward ran. The gate
    consults no outcome data, which is what makes that legitimate.
    """
    from scipy import stats as sps
    rows = []
    for direction, oof in oof_by_direction.items():
        taken = trades_at_policy(oof, direction)
        for asset in survivors:
            sub = taken[taken["asset"] == asset]
            cell = confirmatory_cell(sub, asset, direction, family_size)
            t = cell["t_block_nw"]
            cell["p_value"] = (float(2 * sps.norm.sf(abs(t)))
                               if np.isfinite(t) else np.nan)
            rows.append(cell)
    out = pd.DataFrame(rows)
    if len(out):
        out["p_value_bh"] = bh_adjust(out["p_value"].to_numpy())
        out["significant_bh_05"] = out["p_value_bh"] < 0.05
        out["family_size"] = family_size
        out["arm"] = "P_confirmatory"
    return out


def build_diagnostic_table(cells, arm_name):
    """S10 -- diagnostic arms report UNCORRECTED p-values, explicitly labelled,
    and cannot constitute an M1 success."""
    from scipy import stats as sps
    out = pd.DataFrame(cells)
    if len(out):
        out["p_value_UNCORRECTED"] = [
            float(2 * sps.norm.sf(abs(t))) if np.isfinite(t) else np.nan
            for t in out["t_block_nw"]]
        out["arm"] = arm_name
        out["correction"] = "NONE -- uncorrected, diagnostic only, cannot constitute M1 success"
    return out


def m1_verdict(confirmatory, audits_passed):
    """S10 -- the decision gate.

    M1 succeeds only if Arm P, primary geometry, shows mean net per-trade return
    > 0 with BH-corrected significance at the family threshold, on at least two
    assets, with all audits passing. Anything short of that is a null result and
    is reported as one.
    """
    if len(confirmatory) == 0:
        passing_assets = []
    else:
        ok = (confirmatory["passes_net_positive"]
              & confirmatory["significant_bh_05"]
              & ~confirmatory["suppressed_below_min_blocks"])
        passing_assets = sorted(confirmatory.loc[ok, "asset"].unique().tolist())
    succeeded = bool(len(passing_assets) >= 2 and audits_passed)
    return pd.DataFrame([{
        "m1_succeeded": succeeded,
        "n_passing_assets": len(passing_assets),
        "passing_assets": ",".join(passing_assets),
        "audits_passed": audits_passed,
        "criterion": "Arm P, primary geometry, net>0 AND BH-significant, on >=2 "
                     "assets, all audits passing",
        "verdict": ("M1 SUCCEEDS" if succeeded else
                    "M1 NULL RESULT -- reported as one; the holdout stays sealed"),
        "holdout_unlocked": HOLDOUT_UNLOCKED,
    }])


def combine_and_save(extra_tables=None):
    """S8 of catboostv2.py, adapted -- assemble every registered table into one
    file. OOF frames are written separately (they were bloating _all_results.csv
    past 130MB via column-unioning concat)."""
    for name, df in (extra_tables or {}).items():
        if df is not None and len(df):
            tables_to_combine[name] = df
    tagged = []
    for name, df in tables_to_combine.items():
        if df is None or len(df) == 0:
            continue
        t = df.copy()
        t.insert(0, "table", name)
        tagged.append(t)
    if not tagged:
        return pd.DataFrame()
    combined = pd.concat(tagged, ignore_index=True, sort=False)
    if os.path.isdir(RESULTS_DIR):
        path = os.path.join(RESULTS_DIR, run_tag + "_all_results.csv")
        combined.to_csv(path, index=False)
        print("Combined " + str(len(tagged)) + " tables, " + str(len(combined))
              + " rows -> " + path)
    return combined


