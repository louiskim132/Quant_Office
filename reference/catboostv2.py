# ===========================================================================
class FoldBoundaries:
    """Every boundary for one fold, purged in WALL-CLOCK, with self-verification.

    S6.1: v2 did `fit_end = fit_end_raw - purge_bars` in integer index space
    (catboostv2.py L1682), with indices sourced from `date_bounds`. Stacked
    three assets deep, purging 96 rows removes 32 bars of wall-clock -- a silent
    3x under-purge that fails in the leak-permissive direction, and the single
    most likely mechanical source of a false positive in M1.

    The invariants are stated in wall-clock, not as descriptions of the
    arithmetic, so an implementation that keeps integer arithmetic underneath
    still fails loudly:

        fit_end_ts   + PURGE_BARS * bar_delta <= inner_start_ts
        inner_end_ts + PURGE_BARS * bar_delta <= test_start_ts

    Slices are half-open in time: [start, end).
    """

    __slots__ = ("fit", "inner", "test", "purge_bars", "bar_delta",
                 "purge_delta", "purged_fit_delta", "purged_inner_delta")

    def __init__(self, fit_start_ts, fit_end_raw_ts, inner_start_ts,
                 inner_end_raw_ts, test_start_ts, test_end_ts,
                 purge_bars=PURGE_BARS, bar_delta=BAR_DELTA):
        self.purge_bars = purge_bars
        self.bar_delta = bar_delta
        self.purge_delta = purge_bars * bar_delta

        fit_end_ts = max(fit_start_ts, fit_end_raw_ts - self.purge_delta)
        inner_end_ts = max(inner_start_ts, inner_end_raw_ts - self.purge_delta)
        self.purged_fit_delta = fit_end_raw_ts - fit_end_ts
        self.purged_inner_delta = inner_end_raw_ts - inner_end_ts

        self.fit = (fit_start_ts, fit_end_ts)
        self.inner = (inner_start_ts, inner_end_ts)
        self.test = (test_start_ts, test_end_ts)
        self._verify()

    def _verify(self):
        (fs, fe), (is_, ie), (ts, te) = self.fit, self.inner, self.test
        assert fs <= fe, "S6.1: empty/inverted fit slice [" + str(fs) + "," + str(fe) + ")"
        assert is_ <= ie, "S6.1: empty/inverted inner slice [" + str(is_) + "," + str(ie) + ")"
        assert ts < te, "S6.1: empty test slice [" + str(ts) + "," + str(te) + ")"
        assert fe <= is_, "S6.1: fit overlaps inner (" + str(fe) + " > " + str(is_) + ")"
        assert ie <= ts, "S6.1: inner overlaps test (" + str(ie) + " > " + str(ts) + ")"
        assert fe + self.purge_delta <= is_, (
            "S6.1 PURGE VIOLATION: fit ends at " + str(fe) + ", inner starts at "
            + str(is_) + ", but labels resolve up to " + str(self.purge_delta) + " forward")
        assert ie + self.purge_delta <= ts, (
            "S6.1 PURGE VIOLATION: inner ends at " + str(ie) + ", test starts at "
            + str(ts) + ", but labels resolve up to " + str(self.purge_delta) + " forward")

    def masks(self, frame, time_col="time"):
        """Row masks derived from the shared wall-clock boundaries.

        Boundaries are global across assets; masks are per row. Deriving masks
        this way -- rather than from row positions -- is what makes the purge
        asset-count-independent.
        """
        t = frame[time_col]
        return {
            "fit": (t >= self.fit[0]) & (t < self.fit[1]),
            "inner": (t >= self.inner[0]) & (t < self.inner[1]),
            "test": (t >= self.test[0]) & (t < self.test[1]),
        }

    def sizes(self, frame, time_col="time"):
        m = self.masks(frame, time_col)
        return {"n_fit": int(m["fit"].sum()),
                "n_inner": int(m["inner"].sum()),
                "n_test": int(m["test"].sum()),
                "purged_fit_delta": self.purged_fit_delta,
                "purged_inner_delta": self.purged_inner_delta}


def assert_cross_asset_purge(frame, bounds, time_col="time", asset_col="asset"):
    """S9 B6 -- per-asset boundary check. Raises rather than warns.

    Checked PER ASSET, not on the pooled frame: a pooled check can pass while an
    individual asset's rows straddle the boundary.
    """
    masks = bounds.masks(frame, time_col)
    for asset, grp in frame.groupby(asset_col, sort=False):
        idx = grp.index
        fit_t = frame.loc[idx[masks["fit"].loc[idx]], time_col]
        inner_t = frame.loc[idx[masks["inner"].loc[idx]], time_col]
        test_t = frame.loc[idx[masks["test"].loc[idx]], time_col]
        if len(fit_t) and len(inner_t):
            assert fit_t.max() + bounds.purge_delta <= inner_t.min(), (
                "B6 PURGE VIOLATION (" + str(asset) + "): fit ends " + str(fit_t.max())
                + ", inner starts " + str(inner_t.min()) + ", purge "
                + str(bounds.purge_delta))
        if len(inner_t) and len(test_t):
            assert inner_t.max() + bounds.purge_delta <= test_t.min(), (
                "B6 PURGE VIOLATION (" + str(asset) + "): inner ends " + str(inner_t.max())
                + ", test starts " + str(test_t.min()) + ", purge "
                + str(bounds.purge_delta))
        if len(fit_t) and len(test_t):
            assert fit_t.max() < test_t.min(), (
                "B6 ORDERING VIOLATION (" + str(asset) + "): fit reaches into test")
    return True


def build_fold_schedule(frame, first_test_start=FIRST_TEST_START, fit_days=180,
                        inner_days=30, test_days=10, step_days=10,
                        expanding=False, time_col="time"):
    """S8 -- the walk-forward schedule, in wall-clock.

    M1 (ratified reading): `fit_days` is TOTAL LOOKBACK. The inner slice is
    carved off the END of it, matching v2's semantics, so a 180/30 fold is
    150 days of fit plus 30 days of inner -- not 210 days total. Do not "fix"
    this to fit_start = fit_end_raw - fit_days.

    Rolling: total lookback `fit_days`, inner carved off its end, `test_days`
    test. Expanding: identical inner/test/step from a fixed origin.

    Any purge violation raises out of FoldBoundaries rather than being silently
    skipped -- it is a geometry bug, not a data condition.
    """
    t_min, t_max = frame[time_col].min(), frame[time_col].max()
    origin = t_min
    folds = []
    test_start = pd.Timestamp(first_test_start)
    while test_start + pd.Timedelta(days=test_days) <= t_max:
        inner_end_raw = test_start
        inner_start = inner_end_raw - pd.Timedelta(days=inner_days)
        fit_end_raw = inner_start
        fit_start = (origin if expanding
                     else fit_end_raw - pd.Timedelta(days=fit_days - inner_days))
        if fit_start < t_min:
            fit_start = t_min
        if fit_start >= fit_end_raw:
            test_start += pd.Timedelta(days=step_days)
            continue
        folds.append(FoldBoundaries(
            fit_start_ts=fit_start,
            fit_end_raw_ts=fit_end_raw,
            inner_start_ts=inner_start,
            inner_end_raw_ts=inner_end_raw,
            test_start_ts=test_start,
            test_end_ts=test_start + pd.Timedelta(days=test_days),
        ))
        test_start += pd.Timedelta(days=step_days)
    return folds


