def select_threshold_by_policy(probs, net_returns):
    """Ported verbatim in behaviour from catboostv2.py L1617-1637.

    PRE-REGISTERED RULE: the LOWEST threshold in THRESHOLD_GRID with at least
    MIN_SELECTION_SIGNALS signals in the fold's inner slice AND a net-return
    t-stat >= MIN_SELECTION_TSTAT there. If none qualifies the fold stands down
    and takes no trades (threshold = NaN, never a fallback to a default -- a
    fallback would silently reintroduce a chosen constant).

    KNOWN PROPERTY, recorded not tuned away: a t-stat scales with sqrt(n), so
    "lowest threshold clearing t >= 3" is biased toward the BOTTOM of the grid
    and behaves as "trade at 0.55 unless the recent window looks actively bad".
    Defensible as a stand-down rule; it is NOT threshold optimisation.
    """
    for t in THRESHOLD_GRID:
        mask = probs >= t
        n = int(mask.sum())
        if n < MIN_SELECTION_SIGNALS:
            continue
        selected = net_returns[mask]
        std = selected.std(ddof=1)
        if not np.isfinite(std) or std <= 0:
            continue
        tstat = selected.mean() / (std / np.sqrt(n))
        if tstat >= MIN_SELECTION_TSTAT:
            return t, n, tstat
    return np.nan, 0, np.nan


def add_execution_price(frame):
    """next_open, per asset and epoch-aware.

    shift(-1) is forward-looking by construction and legitimate: it is the price
    the trade actually fills at, matching catboostv2.py L1755. Epoch-aware so no
    fill price is taken across a discontinuity.
    """
    out = frame.copy()
    out["next_open"] = epoch_shift(out, "open", -1)

    # R9: the join invariant, ASSERTED rather than reasoned about. next_open at
    # row i must be the open of row i+1 within the same (asset, epoch). An
    # off-by-one here is invisible to B3 (which validates feature construction)
    # and to B4 (which validates fold geometry), and is the single most likely
    # source of a false positive in this pipeline. Correct-by-reading is the
    # state the R2 ewm defect was in before it was found.
    expect = epoch_shift(out, "open", -1)
    both = out["next_open"].notna() & expect.notna()
    assert bool((out.loc[both, "next_open"] == expect[both]).all()),         "R9: next_open does not equal the following bar's open within epoch"
    assert bool((out["next_open"].notna() == expect.notna()).all()),         "R9: next_open null pattern disagrees with the epoch-shifted open"
    return out


