def geometry_selection(inner_rolling, inner_expanding, results_expanding):
    """S8 -- the registered rolling-vs-expanding rule, two statistics with
    precedence fixed in advance.

    GOVERNING: paired inner-slice log-loss. Both geometries are fit per fold;
    the inner slice is held out from fitting and strictly precedes the test
    slice, so this touches no test economics and answers "does old data help?"
    directly rather than by proxy. Same-seed pairing (the expanding arm has one
    seed, and an unpaired comparison would mix seed variance into the geometry
    difference). NW at lag ceil(INNER_DAYS / STEP_DAYS) = 3, because adjacent
    folds share ~20 of 30 inner days.

    CORROBORATIVE: AUC regressed on age-of-oldest-training-row, expanding arm.

    If the two disagree, report BOTH geometries and select neither.
    """
    lag = int(np.ceil(INNER_VAL_DAYS / 10))              # 3 at a 10-day step
    merged = inner_rolling.merge(
        inner_expanding, on=["fold", "direction"], suffixes=("_roll", "_exp"))

    # R11: the governing statistic is only meaningful where early stopping and
    # scoring used disjoint rows. If ANY contributing fold degenerated, the
    # selection is refused outright rather than reported with a caveat -- a
    # caveat on a registered selection rule is how an uncitable number becomes a
    # cited one.
    citable_cols = [c for c in ("geometry_citable_roll", "geometry_citable_exp")
                    if c in merged.columns]
    all_citable = (bool(merged[citable_cols].all().all())
                   if citable_cols and len(merged) else False)
    if not all_citable:
        return pd.DataFrame([{
            "n_paired_folds": int(len(merged)), "nw_lag": lag,
            "mean_inner_logloss_diff_exp_minus_roll": np.nan,
            "t_nw_paired": np.nan, "expanding_better_governing": False,
            "auc_vs_age_slope": np.nan, "auc_vs_age_pvalue": np.nan,
            "drift_detected_corroborative": False,
            "paired_on": "seed0 (common to both arms)",
            "selected_geometry": "NOT_CITABLE",
            "basis": ("R11: inner slice could not be split into disjoint "
                      "stopping and scoring parts on at least one fold, so "
                      "inner_logloss is contaminated by early stopping. No "
                      "geometry claim is made from this run."),
        }])
    # Paired on the FIRST SEED, which both arms share. Using the ensemble mean
    # here would be the unpaired comparison the registered rule forbids.
    diff = (merged["inner_logloss_seed0_exp"]
            - merged["inner_logloss_seed0_roll"]).to_numpy()
    t_nw, mean_diff, n = newey_west_tstat(diff, lag=lag)
    # Expanding wins iff its inner log-loss is LOWER (negative difference).
    expanding_better = bool(np.isfinite(t_nw) and mean_diff < 0 and t_nw < -1.96)

    slope = p_slope = np.nan
    if len(results_expanding) > 3:
        sub = results_expanding.dropna(subset=["auc", "oldest_train_row_age_days"])
        if len(sub) > 3 and sub["oldest_train_row_age_days"].nunique() > 1:
            from scipy import stats as sps
            reg = sps.linregress(sub["oldest_train_row_age_days"], sub["auc"])
            slope, p_slope = float(reg.slope), float(reg.pvalue)
    drift_detected = bool(np.isfinite(slope) and slope < 0
                          and np.isfinite(p_slope) and p_slope < 0.05)

    if expanding_better and not drift_detected:
        selected, basis = "expanding", "inner log-loss favours expanding; no AUC drift"
    elif (not expanding_better) and drift_detected:
        selected, basis = "rolling", "inner log-loss does not favour expanding; AUC drift present"
    elif expanding_better and drift_detected:
        selected, basis = "REPORT_BOTH", "statistics disagree; select neither (S8)"
    else:
        selected, basis = "rolling", "expanding not favoured; rolling stands (S8 default)"

    return pd.DataFrame([{
        "n_paired_folds": n, "nw_lag": lag,
        "mean_inner_logloss_diff_exp_minus_roll": mean_diff,
        "paired_on": "seed0 (common to both arms); the ensemble mean is NOT used here",
        "t_nw_paired": t_nw, "expanding_better_governing": expanding_better,
        "auc_vs_age_slope": slope, "auc_vs_age_pvalue": p_slope,
        "drift_detected_corroborative": drift_detected,
        "selected_geometry": selected, "basis": basis,
    }])


def within_window_drift(oof_df, direction):
    """S8 -- registered within-window drift diagnostic: days 1-5 vs 6-10 of each
    test slice. A systematic degradation is the R7.6 calibration cost made
    visible. Recorded, not corrected for, this revision."""
    d = annotate_returns(oof_df, direction)
    if len(d) == 0:
        return pd.DataFrame()
    d["day_in_window"] = (d["time"] - pd.to_datetime(d["test_start"])).dt.days
    d["half"] = np.where(d["day_in_window"] < 5, "days_1_5", "days_6_10")
    rows = []
    for (asset, half), grp in d.groupby(["asset", "half"], sort=True):
        rows.append({"asset": asset, "direction": direction, "half": half,
                     "n_trades": len(grp),
                     "mean_net_return": float(grp["net_return"].mean()),
                     "win_rate": float(grp["target"].mean())})
    return pd.DataFrame(rows)

