def _safe_ratio(num, den):
    den = np.asarray(den, dtype=float)
    good = den > 0
    return np.where(good, np.asarray(num, dtype=float) / np.where(good, den, 1.0), np.nan)


def _rogers_satchell(frame, window, epoch_col="epoch"):
    """Rogers-Satchell realised volatility over `window` bars, epoch-aware.

    RS variance per bar: ln(h/c)ln(h/o) + ln(l/c)ln(l/o). Drift-independent and
    needs no session close, which is why it survives S1 for continuous markets.
    """
    o = frame["open"].to_numpy(dtype=float)
    h = frame["high"].to_numpy(dtype=float)
    lo = frame["low"].to_numpy(dtype=float)
    c = frame["close"].to_numpy(dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        rs = (np.log(h / c) * np.log(h / o)) + (np.log(lo / c) * np.log(lo / o))
    rs = np.where(np.isfinite(rs), rs, np.nan)
    work = frame[["asset", epoch_col]].copy()
    work["_rs"] = rs
    var = epoch_rolling(work, "_rs", window, window, "mean", epoch_col=epoch_col)
    return np.sqrt(var.clip(lower=0))


def _epoch_rolling_corr(frame, col_a, col_b, window, epoch_col="epoch"):
    """Trailing Pearson correlation of two columns, epoch-aware and per asset.

    Computed from rolling moments rather than rolling.corr so the window and
    min_periods semantics match the rest of S4 exactly.
    """
    work = frame[["asset", epoch_col]].copy()
    work["_a"] = frame[col_a]
    work["_b"] = frame[col_b]
    work["_ab"] = frame[col_a] * frame[col_b]
    work["_aa"] = frame[col_a] ** 2
    work["_bb"] = frame[col_b] ** 2
    ma = epoch_rolling(work, "_a", window, window, "mean", epoch_col=epoch_col)
    mb = epoch_rolling(work, "_b", window, window, "mean", epoch_col=epoch_col)
    mab = epoch_rolling(work, "_ab", window, window, "mean", epoch_col=epoch_col)
    maa = epoch_rolling(work, "_aa", window, window, "mean", epoch_col=epoch_col)
    mbb = epoch_rolling(work, "_bb", window, window, "mean", epoch_col=epoch_col)
    cov = mab - ma * mb
    va = (maa - ma * ma).clip(lower=0)
    vb = (mbb - mb * mb).clip(lower=0)
    return _safe_ratio(cov.to_numpy(), np.sqrt(va.to_numpy() * vb.to_numpy()))


def build_features(frame, verbose=True):
    """S4 -- the thirteen features, all epoch-aware and per asset.

    Pure function of a price frame, so the B3 truncation audit can re-run it on
    truncated copies. Every constant it uses is fixed, not data-derived, so the
    pipeline satisfies: a feature at bar t computed through T equals the same
    feature at bar t computed through any T' > t.
    """
    df = frame.copy()
    if "epoch" not in df.columns:
        df = assign_epochs(df)

    # --- Returns (4) -------------------------------------------------------
    df["_log_close"] = np.log(df["close"])
    for horizon, name in ((1, "ret_1"), (4, "ret_4"), (16, "ret_16"), (96, "ret_96")):
        df[name] = epoch_diff(df, "_log_close", periods=horizon)

    # --- Volatility (3) ----------------------------------------------------
    df["rs_vol_96"] = _rogers_satchell(df, 96)
    df["rs_vol_16"] = _rogers_satchell(df, 16)
    df["vol_term_ratio"] = _safe_ratio(df["rs_vol_16"].to_numpy(),
                                       df["rs_vol_96"].to_numpy())

    # --- Range and candle structure (4) ------------------------------------
    candle_range = (df["high"] - df["low"]).to_numpy(dtype=float)
    # S4 zero-range guard. close_position on a zero-range bar is NaN, not 0.5:
    # such a bar carries no positional information, and 0.5 would assert a
    # neutrality that was not observed.
    df["close_position"] = _safe_ratio(
        df["close"].to_numpy() - df["low"].to_numpy(), candle_range)
    df["body_ratio"] = _safe_ratio(
        df["close"].to_numpy() - df["open"].to_numpy(), candle_range)

    df["_range"] = candle_range
    range_mean = epoch_rolling(df, "_range", 96, 96, "mean")
    range_std = epoch_rolling(df, "_range", 96, 96, "std")
    df["range_z_96"] = _safe_ratio(df["_range"].to_numpy() - range_mean.to_numpy(),
                                   range_std.to_numpy())

    df["_abs_dclose"] = epoch_diff(df, "close", periods=1).abs()
    path_num = epoch_diff(df, "close", periods=12).abs()
    path_den = epoch_rolling(df, "_abs_dclose", 12, 12, "sum")
    df["path_efficiency_12"] = _safe_ratio(path_num.to_numpy(), path_den.to_numpy())

    # --- Volume (2) --------------------------------------------------------
    vol_mean = epoch_rolling(df, "volume", 96, 96, "mean")
    vol_std = epoch_rolling(df, "volume", 96, 96, "std")
    df["volume_z_96"] = _safe_ratio(df["volume"].to_numpy() - vol_mean.to_numpy(),
                                    vol_std.to_numpy())

    # S4: correlated against log(volume), NOT volume_z_96, whose normalisation
    # moves within the correlation window.
    #
    # M4: log(volume) is NaN on a zero-volume bar, and with min_periods = window
    # one such bar nulls a 96-bar stretch. That is correct under the
    # no-forward-fill constraint and is NOT relaxed -- but early XRP carries
    # these bars, so the effect is made visible in the per-year coverage table
    # rather than left to be discovered later.
    df["_abs_ret_1"] = df["ret_1"].abs()
    df["_log_volume"] = np.log(df["volume"].where(df["volume"] > 0))
    df["volume_return_corr_96"] = _epoch_rolling_corr(df, "_abs_ret_1", "_log_volume", 96)

    df = df.drop(columns=[c for c in df.columns if c.startswith("_")])

    if verbose:
        cov = {f: float(df[f].notna().mean()) for f in FEATURE_COLS}
        print("S4: " + str(len(FEATURE_COLS)) + " features built; overall coverage "
              + ", ".join(k + "=" + format(v, ".3f") for k, v in cov.items()))
    return df, FEATURE_COLS


def feature_coverage_table(featured, feature_cols=None):
    """M4 -- per-asset, per-year coverage for all 13 features.

    Reporting only. No min_periods is relaxed: the point is that gap-driven and
    zero-volume-driven coverage loss is visible in a table rather than inferred.
    """
    feature_cols = feature_cols or FEATURE_COLS
    rows = []
    for (asset, year), grp in featured.groupby(
            ["asset", featured["time"].dt.year], sort=True):
        row = {"asset": asset, "year": int(year), "n_rows": len(grp),
               "n_observed_bars": int(grp["close"].notna().sum())}
        for f in feature_cols:
            row["cov_" + f] = round(float(grp[f].notna().mean()), 4)
        rows.append(row)
    out = pd.DataFrame(rows)
    save_section_csv(out, "s4_feature_coverage_by_year")
    return out

