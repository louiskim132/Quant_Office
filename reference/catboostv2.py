def bh_adjust(pvalues):
    """Benjamini-Hochberg adjusted p-values, carried from v2 unchanged."""
    p = np.asarray(pvalues, dtype=float)
    out = np.full(p.shape, np.nan)
    ok = np.isfinite(p)
    if not ok.any():
        return out
    vals = p[ok]
    n = len(vals)
    order = np.argsort(vals)
    adj = vals[order] * n / np.arange(1, n + 1)
    adj = np.minimum.accumulate(adj[::-1])[::-1]
    restored = np.empty(n)
    restored[order] = np.clip(adj, 0, 1)
    out[ok] = restored
    return out

