def wilder_atr(frame, period=ATR_PERIOD, epoch_col="epoch"):
    """S5 -- Wilder ATR, epoch-aware, per asset.

    Wilder smoothing is ewm(alpha=1/period, adjust=False), which is
    truncation-invariant: the value at bar t depends only on bars <= t.

    G1 consequence: pandas `ewm.mean()` SKIPS NaN inputs and carries the
    previous value forward, which after the grid fill would be a forward-fill
    through a gap by the back door -- exactly what S1 forbids.

    R2: masking the OUTPUT is not sufficient, because it does not address the
    STATE. A skipped NaN contributes zero decay, so after a 95-bar gap the first
    unmasked ATR still embedded pre-gap true ranges at full weight, as though
    the bar 24 hours earlier were adjacent -- and ATR sets barrier width, so it
    propagated into sl_dist, cost_feasible, the binding rate and every label.
    Not a leak (no future information), but a silent construction defect of the
    same family as vol_of_vol, invisible to every registered audit.

    The fix groups the ewm by CONTIGUOUS OBSERVED RUN, so the accumulator
    restarts after any gap, however short. Epoch grouping handles long gaps once
    R1 makes epochs splittable; the run-level reset handles sub-tolerance gaps
    inside an epoch. Both are required. The output mask is retained as
    belt-and-braces rather than as the sole defence.

    On the first bar of a run there is no previous close, so true range falls
    back to (high - low). Recorded as a construction choice: it affects at most
    one bar per run.
    """
    prev_close = epoch_shift(frame, "close", 1, epoch_col=epoch_col)
    hl = frame["high"] - frame["low"]
    tr = np.maximum(hl, np.maximum((frame["high"] - prev_close).abs(),
                                   (frame["low"] - prev_close).abs()))
    tr = tr.fillna(hl)
    work = frame[["asset", epoch_col]].copy()
    work["_tr"] = tr
    work["_run"] = observed_run_id(frame, "close", epoch_col=epoch_col)
    atr = (work.groupby(["asset", epoch_col, "_run"], sort=False)["_tr"]
               .transform(lambda s: s.ewm(alpha=1.0 / period, adjust=False,
                                          min_periods=period).mean()))
    observed = (work.groupby(["asset", epoch_col, "_run"], sort=False)["_tr"]
                    .transform(lambda s: s.rolling(period, min_periods=1).count()))
    return atr.where(observed.to_numpy() >= period)


def add_atr(frame, period=ATR_PERIOD):
    """Attach atr14 and its one-bar lag.

    S5: the lag is not because bar i is incomplete -- it is complete at the
    decision point. It is for consistency with sigma_rs_lagged, and because it
    decouples barrier width from the same bar whose close sets the entry, a
    coupling the truncation audit cannot reason about. Cost: one bar of
    responsiveness.
    """
    out = frame.copy()
    out["atr14"] = wilder_atr(out, period=period)
    out["atr14_lagged"] = epoch_shift(out, "atr14", 1)
    return out


# Resolution status codes returned by the forward scan.
RES_TP = 1
RES_SL = 0
RES_HORIZON = -1        # MAX_HORIZON reached with neither barrier touched
RES_EPOCH_END = -2      # epoch ended first: the path is unobserved, not slow
RES_GAP = -3            # G1: a gap row inside the scan window; path unobserved

UNOBSERVED_STATUSES = (RES_EPOCH_END, RES_GAP)


def _scan_epoch(high, low, close, sl_dist, direction, tp_multiplier,
                max_horizon, entry_stride, entry_offset):
    """Forward first-passage scan within a single (asset, epoch) block.

    Returns (idx, status, bars, tp_price, sl_price) for the scanned entries.

    S3.1: `entry_stride` subsamples ENTRIES only. The forward scan always runs
    at full resolution -- striding the scan would corrupt first-passage times,
    while striding entries leaves the rates it feeds unbiased.

    G1: a gap row inside the scan window terminates the scan as RES_GAP. Before
    this, NaN high/low made both hit comparisons False and the bar passed
    through silently, so an UNOBSERVED path was scored as "no touch" -- which
    inflates the horizon-binding rate the S3.1 ceiling gates on, and would have
    produced labels from price paths that were never seen.
    """
    n = len(close)
    idx_all = np.arange(entry_offset, max(entry_offset, n - 1), entry_stride)
    out_idx, out_status, out_bars = [], [], []
    out_tp, out_sl = [], []

    for i in idx_all:
        d = sl_dist[i]
        entry = close[i]
        # No entry on a gap row: there is no close to enter at.
        if not np.isfinite(d) or d <= 0 or not np.isfinite(entry):
            continue
        tp_d = tp_multiplier * d
        if direction == "long":
            sl_price, tp_price = entry - d, entry + tp_d
        else:
            sl_price, tp_price = entry + d, entry - tp_d

        status, bars = RES_EPOCH_END, np.nan
        end = min(i + 1 + max_horizon, n)
        for j in range(i + 1, end):
            hj, lj = high[j], low[j]
            if not (np.isfinite(hj) and np.isfinite(lj)):
                status, bars = RES_GAP, np.nan
                break
            if direction == "long":
                hit_sl = lj <= sl_price
                hit_tp = hj >= tp_price
            else:
                hit_sl = hj >= sl_price
                hit_tp = lj <= tp_price
            # S5: simultaneous hit resolves against us, unchanged from v2.
            if hit_sl and hit_tp:
                status, bars = RES_SL, j - i
                break
            if hit_tp:
                status, bars = RES_TP, j - i
                break
            if hit_sl:
                status, bars = RES_SL, j - i
                break
        else:
            # Distinguish "the horizon bound", which is training-set attrition
            # the S3.1 ceiling governs, from "the epoch ran out", which is a
            # data boundary and is not evidence about barrier width.
            status = RES_HORIZON if end == i + 1 + max_horizon else RES_EPOCH_END

        out_idx.append(i)
        out_status.append(status)
        out_bars.append(bars)
        out_tp.append(tp_price)
        out_sl.append(sl_price)

    return (np.asarray(out_idx, dtype=np.int64),
            np.asarray(out_status, dtype=np.int64),
            np.asarray(out_bars, dtype=float),
            np.asarray(out_tp, dtype=float),
            np.asarray(out_sl, dtype=float))


def first_passage(frame, direction, multiplier, tp_multiplier=TP_MULTIPLIER,
                  max_horizon=MAX_HORIZON, entry_stride=1, epoch_col="epoch",
                  progress=False):
    """S5 -- triple-barrier first passage over a stacked frame.

    sl_dist = multiplier * atr14_lagged, per S5. `multiplier` is per asset when
    a dict is passed, matching S3.2's per-asset m.
    """
    assert direction in ("long", "short")
    # R12 note: `row_pos` carries INDEX LABELS of the frame passed in, which is
    # well-defined for any index. The RangeIndex requirement belongs at the
    # .loc-WRITING site (label_targets), not here -- horizon_binding_rate,
    # admissible_window and power_projection all pass filtered slices and use
    # only `status`, so asserting a RangeIndex here would break the S3 gate
    # without protecting anything.
    if "atr14_lagged" not in frame.columns:
        raise ValueError("first_passage requires atr14_lagged; call add_atr first")

    pieces = []
    groups = list(frame.groupby(["asset", epoch_col], sort=False))
    it = tqdm(groups, desc="first_passage(" + direction + ")") if progress else groups
    for (asset, epoch), grp in it:
        m = multiplier[asset] if isinstance(multiplier, dict) else multiplier
        if m is None or not np.isfinite(m):
            continue
        sl_dist = (m * grp["atr14_lagged"]).to_numpy(dtype=float)
        idx, status, bars, tp_px, sl_px = _scan_epoch(
            grp["high"].to_numpy(dtype=float),
            grp["low"].to_numpy(dtype=float),
            grp["close"].to_numpy(dtype=float),
            sl_dist, direction, tp_multiplier, max_horizon,
            entry_stride, 0)
        if len(idx) == 0:
            continue
        pieces.append(pd.DataFrame({
            "row_pos": grp.index.to_numpy()[idx],
            "asset": asset,
            "epoch": epoch,
            "time": grp["time"].to_numpy()[idx],
            "close": grp["close"].to_numpy()[idx],
            "sl_dist": sl_dist[idx],
            "status": status,
            "bars_to_resolution": bars,
            "tp_price": tp_px,
            "sl_price": sl_px,
        }))

    cols = ["row_pos", "asset", "epoch", "time", "close", "sl_dist", "status",
            "bars_to_resolution", "tp_price", "sl_price"]
    if not pieces:
        return pd.DataFrame(columns=cols)
    return (pd.concat(pieces, ignore_index=True)
              .sort_values(["time", "asset"]).reset_index(drop=True))


def label_targets(frame, direction, multiplier, tp_multiplier=TP_MULTIPLIER,
                  max_horizon=MAX_HORIZON, progress=True):
    """S5 -- single-arm ATR labeling. Replaces v2's two-arm `label_targets`;
    the `barrier_mode` parameter and both arms are deleted, not disabled.

    `cost_feasible` is recorded per row but NOT used to filter the training set,
    unchanged from v2: gating is applied at evaluation only, so training-set
    composition is not a second moving part.
    """
    # R12: this function writes via .loc using positions taken from the frame
    # index. That is positionally correct only on a RangeIndex; a caller passing
    # a filtered frame without resetting gets silent misalignment.
    assert frame.index.equals(pd.RangeIndex(len(frame))), (
        "R12: label_targets writes by .loc on positions taken from the frame "
        "index; pass a reset-index frame")
    fp = first_passage(frame, direction, multiplier, tp_multiplier,
                       max_horizon, entry_stride=1, progress=progress)
    out = frame.copy()
    for col in ("target", "bars_to_resolution", "tp_price", "sl_price",
                "sl_dist", "cost_feasible", "resolution_status"):
        out[col] = np.nan
    out["direction"] = direction
    if len(fp) == 0:
        return out

    resolved = fp["status"].isin([RES_TP, RES_SL]).to_numpy()
    pos = fp["row_pos"].to_numpy()
    out.loc[pos[resolved], "target"] = fp.loc[resolved, "status"].to_numpy(dtype=float)
    out.loc[pos, "bars_to_resolution"] = fp["bars_to_resolution"].to_numpy()
    out.loc[pos, "tp_price"] = fp["tp_price"].to_numpy()
    out.loc[pos, "sl_price"] = fp["sl_price"].to_numpy()
    out.loc[pos, "sl_dist"] = fp["sl_dist"].to_numpy()
    out.loc[pos, "resolution_status"] = fp["status"].to_numpy()

    tp_pct = (tp_multiplier * fp["sl_dist"] / fp["close"]).to_numpy()
    floors = fp["asset"].map(cost_floor_fractional).to_numpy(dtype=float)
    out.loc[pos, "cost_feasible"] = (tp_pct >= floors).astype(float)

    # R9: bars_to_resolution must count forward from i+1, so the resolution
    # timestamp is entry_time + bars_to_resolution * BAR_DELTA and lands inside
    # the same epoch.
    res = out.dropna(subset=["bars_to_resolution"])
    if len(res):
        assert bool((res["bars_to_resolution"] >= 1).all()),             "R9: bars_to_resolution below 1 -- the scan did not start at i+1"
        assert bool((res["bars_to_resolution"] <= max_horizon).all()),             "R9: bars_to_resolution above MAX_HORIZON"
    return out


def realized_binding_rate(labelled):
    """G2 -- realized horizon-binding rate per asset, at entry_stride = 1.

    Denominator excludes unobserved paths (epoch end, gap rows), matching the
    S3.1 gate's construction: a data boundary is not evidence about barrier
    width.
    """
    rows = []
    for asset, grp in labelled.groupby("asset", sort=False):
        status = grp["resolution_status"].dropna()
        scanned = status[~status.isin(UNOBSERVED_STATUSES)]
        rate = float((scanned == RES_HORIZON).mean()) if len(scanned) else np.nan
        rows.append({"asset": asset, "n_scanned": int(len(scanned)),
                     "n_horizon_bound": int((scanned == RES_HORIZON).sum()),
                     "realized_binding_rate": rate})
    return pd.DataFrame(rows)

