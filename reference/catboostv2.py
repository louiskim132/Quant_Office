def main(run_walkforward_stage=True, frames=None, model_params=None, seeds=None,
         fold_kwargs=None):
    """S12 -- the full pipeline.

    `frames` / `model_params` / `seeds` / `fold_kwargs` exist so the synthetic
    suite can drive this end to end without Drive or a GPU. They change nothing
    about a real run: with all four omitted, the registered constants govern.
    """
    seeds = seeds or SEEDS
    model_params = model_params or MODEL_PARAMS
    fold_kwargs = fold_kwargs or dict(fit_days=180, inner_days=30,
                                      test_days=10, step_days=10)
    print("=== Recatboost / M1 v3 (round-3 revision). Walk-forward gated on S3. ===")

    # S7.7 / O10: the register must EXIST BEFORE the run, so M1's row is
    # appended on completion rather than reconstructed afterwards.
    bootstrap_lineage_register()

    # Step 1 -- assembly (G1: regular grid, gaps as NaN rows).
    stacked = assemble(frames=frames)
    print("S2: " + str(len(stacked)) + " grid rows, "
          + str(int(stacked["close"].notna().sum())) + " observed bars, "
          + str(stacked["asset"].nunique()) + " assets, "
          + str(stacked["time"].min()) + " .. " + str(stacked["time"].max()))
    print("S2: epochs per asset -> "
          + str(stacked.groupby("asset")["epoch"].nunique().to_dict()))

    # G4 -- spreads must have provenance before anything charges a cost.
    spreads = derive_spreads(stacked)
    print("G4 spreads (Corwin-Schultz, warm-up prefix): "
          + str({a: round(v, 6) for a, v in spreads.items()}))

    stacked = add_atr(stacked)

    # Step 2 -- the blocking gate.
    survivors, m_by_asset, verdict = run_gate(stacked)
    print("S3 verdict: " + str(verdict))
    if verdict["terminated"]:
        print("M1 TERMINATED at the S3 gate. No walk-forward, no single-asset run.")
        return stacked, survivors, m_by_asset

    t_k = BH_T_BY_FAMILY[int(verdict["confirmatory_family_size"])]
    proj = power_projection(stacked, m_by_asset, survivors, t_k)
    if len(proj):
        print(proj.to_string(index=False))

    stacked = stacked[stacked["asset"].isin(survivors)].reset_index(drop=True)

    # Step 5 -- features.
    featured, feature_cols = build_features(stacked)
    save_section_csv(
        pd.DataFrame([{"feature": k, "rationale": v}
                      for k, v in FEATURE_RATIONALE.items()]),
        "s4_feature_rationale")
    feature_coverage_table(featured, feature_cols)      # M4

    # Step 6 -- labeling, both directions, surviving assets only.
    labelled = {}
    for direction in ("long", "short"):
        # add_execution_price attaches next_open (epoch-aware), which every
        # downstream cost calculation and the walk-forward's dropna require.
        labelled[direction] = add_execution_price(
            label_targets(featured, direction, m_by_asset))
        lab = labelled[direction]
        print("S5 " + direction + ": " + str(int(lab["target"].notna().sum()))
              + " labelled, base rate "
              + format(float(lab["target"].mean(skipna=True)), ".4f")
              + " vs breakeven " + format(BREAKEVEN_WIN_RATE, ".4f"))

    # G2 -- the S3.2 escape valve. Raises on failure; this is a registered stop.
    audit = audit_realized_binding(labelled, m_by_asset)
    print("S3.2 realized-binding audit:\n" + audit.to_string(index=False))

    # --- Step 7: audits, BEFORE any walk-forward result is produced ---------
    print("\n=== S9 B3 -- truncation invariance + planted-leak detector validation ===")
    b3 = run_truncation_audit(featured[["asset", "time", "open", "high", "low",
                                        "close", "volume", "epoch"]],
                              FEATURE_COLS)
    save_section_csv(b3, "s9_b3_truncation_audit")
    b3_clean = bool(len(b3)) and bool((b3["status"] == "PASS").all())
    print("B3: " + ("PASS" if b3_clean else "FAIL")
          + " (" + str(int((b3["status"] == "LOOKAHEAD").sum())) + " lookahead flags)")

    detector = validate_truncation_detector(
        featured[["asset", "time", "open", "high", "low", "close", "volume", "epoch"]])
    save_section_csv(detector, "s9_b3_planted_leak_validation")
    print(detector.to_string(index=False))
    detector_ok = bool(detector["detector_ok"].iloc[0]) if len(detector) else False
    print("B3 detector: " + ("OK" if detector_ok else "FAILED")
          + ", detection rate " + str(detector["detection_rate"].iloc[0])
          + " (a miss on a registered low-power probe is recorded, not a failure)")
    save_section_csv(LEAK_AUDIT_KNOWN_LIMITATIONS, "s9_leak_audit_known_limitations")

    # R9: the join invariant is asserted in add_execution_price and
    # label_targets; this proves the pipeline would NOTICE if it failed.
    align = validate_alignment_detector(featured, m_by_asset,
                                        model_params=model_params,
                                        fold_kwargs=fold_kwargs)
    save_section_csv(align, "s9_r9_alignment_detector")
    if len(align):
        print(align.to_string(index=False))
    pf = align[align["is_passfail"]] if len(align) else align
    align_ok = bool(len(pf)) and bool((pf["verdict"] == "DETECTOR_OK").all())
    print("R9 alignment detector: " + ("OK" if align_ok else "BLIND"))
    if not align_ok:
        print("  *** The pipeline cannot distinguish correctly-aligned features "
              "from next-bar features. No walk-forward result from this run is "
              "citable. ***")

    folds_rolling = build_fold_schedule(featured, FIRST_TEST_START, **fold_kwargs)
    folds_expanding = build_fold_schedule(featured, FIRST_TEST_START,
                                          expanding=True, **fold_kwargs)
    print("S8: " + str(len(folds_rolling)) + " rolling folds, "
          + str(len(folds_expanding)) + " expanding")

    if not run_walkforward_stage:
        return featured, labelled, m_by_asset

    # S9 B4 -- pooled AND per asset. A pooled null can pass while one asset
    # carries a leak the other two dilute below detection.
    print("\n=== S9 B4 -- shuffled-label null + canary ===")
    b4_rows = []
    for direction in ("long", "short"):
        b4_rows.append(run_null_and_canary(labelled[direction], FEATURE_COLS,
                                           folds_rolling, direction, label="pooled",
                                           model_params=model_params))
        for asset in survivors:
            sub = labelled[direction]
            b4_rows.append(run_null_and_canary(
                sub[sub["asset"] == asset], FEATURE_COLS, folds_rolling,
                direction, label=asset, model_params=model_params))
    b4 = pd.concat(b4_rows, ignore_index=True)
    save_section_csv(b4, "s9_b4_null_canary")
    print(b4.to_string(index=False))
    b4_ok = bool((~b4["verdict"].isin(
        ["LEAK_SUSPECTED", "INSUFFICIENT_POWER", "DETECTOR_BLIND"])).all())

    audits_passed = bool(b3_clean and detector_ok and b4_ok and align_ok)
    print("\nAudit roll-up: B3=" + str(b3_clean) + " detector=" + str(detector_ok)
          + " B4=" + str(b4_ok) + " R9_align=" + str(align_ok)
          + " -> audits_passed=" + str(audits_passed))

    # --- Step 8: walk-forward. Arm P first and checkpointed. ----------------
    family_size = int(verdict["confirmatory_family_size"])
    # S11: every arm is fingerprinted and checkpointed as it completes, so a
    # disconnect costs one arm rather than the run.
    fp = config_fingerprint({
        "m": tuple(sorted((k, round(v, 6)) for k, v in m_by_asset.items())),
        "spreads": tuple(sorted((k, round(v, 8)) for k, v in SPREAD_PCT.items())),
        "features": tuple(FEATURE_COLS), "survivors": tuple(sorted(survivors)),
        "folds": tuple(sorted(fold_kwargs.items())), "seeds": tuple(seeds),
        "model": tuple(sorted((k, str(v)) for k, v in model_params.items())),
        "tp": TP_MULTIPLIER, "horizon": MAX_HORIZON,
        "gap": (str(STABLE_GAP_LIMIT), GAP_TOLERANCE_BARS),
        "first_test": str(FIRST_TEST_START),
    })
    print("S11: configuration fingerprint " + fp)

    oof_p, res_p, inner_p = {}, {}, {}
    imp_rows, perm_rows = [], []
    for direction in ("long", "short"):
        wf = run_or_resume(
            "P_rolling_" + direction, fp,
            lambda direction=direction: run_walkforward(
                labelled[direction], FEATURE_COLS, folds_rolling,
                direction, label="P_rolling_" + direction,
                seeds=seeds, model_params=model_params, collect_inner=True,
                run_permutation=RUN_PERMUTATION_IMPORTANCE,
                save_importance=SAVE_PER_FOLD_DETAIL))
        r, o, i = wf[0], wf[1], wf[2]
        res_p[direction], oof_p[direction], inner_p[direction] = r, o, i
        if hasattr(wf, "importance") and len(wf.importance):
            imp_rows.append(wf.importance)
        if hasattr(wf, "permutation") and len(wf.permutation):
            perm_rows.append(wf.permutation)
        save_section_csv(r, "s7_foldresults_P_rolling_" + direction)

    if imp_rows:
        imp = pd.concat(imp_rows, ignore_index=True)
        save_section_csv(imp, "s7_feature_importance_by_fold")
        save_section_csv(
            imp.groupby(["direction", "feature"], as_index=False)["importance"]
               .agg(mean_importance="mean", std_importance="std",
                    n_folds="size")
               .sort_values(["direction", "mean_importance"], ascending=[True, False]),
            "s7_feature_importance_summary")
    if perm_rows:
        perm = pd.concat(perm_rows, ignore_index=True)
        save_section_csv(perm, "s7_permutation_importance_by_fold")
        save_section_csv(summarise_permutation(perm), "s7_permutation_importance_summary")

